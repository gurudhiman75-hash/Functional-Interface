function entityId(classId: string, index: number): string {
  return `${classId.replace(/^CLS_/, "CLS_ENT_")}_${String(index + 1).padStart(2, "0")}`;
}

export const CLS_CP001_ENTITIES: readonly SemanticEntity[] = CLASS_SEEDS.flatMap((seed) =>
  seed.members.map((label, index) => ({
    entityId: entityId(seed.classId, index),
    label,
    classIds: [seed.classId] as const,
  })),
);

export const CLS_CP001_CLASSES: readonly SemanticClass[] = CLASS_SEEDS.map((seed) => ({
  classId: seed.classId,
  label: seed.label,
  family: seed.family,
  contrastGroup: seed.contrastGroup,
  surfaceKind: seed.surfaceKind,
  qualityRank: seed.qualityRank,
  memberEntityIds: seed.members.map((_, index) => entityId(seed.classId, index)),
  explanation: seed.explanation,
  shortcut: seed.shortcut,
  trap: seed.trap,
}));

