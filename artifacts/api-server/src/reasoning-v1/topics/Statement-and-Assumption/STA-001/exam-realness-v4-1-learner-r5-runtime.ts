function polishEnglishR5(text: string): string {
  return text
    .replace(/^Requests for support requests are processed through (.+)\.$/u, "Support requests are processed through $1.")
    .replace(/Achieving fewer repeat visits is reasonably connected with implementing/gu, "Reducing repeat visits is reasonably connected with implementing")
    .replace(/to gain fewer repeat visits/gu, "to reduce repeat visits")
    .replace(/to achieve fewer repeat visits/gu, "to reduce repeat visits")
    .replace(/producing fewer repeat visits/gu, "reducing repeat visits")
    .replace(/The benefit of fewer repeat visits is relevant to/gu, "The benefit of reducing repeat visits is relevant to")
    .replace(/^The expected effect of (.+) is relevant to (.+)\.$/u, "The effect of $1 can plausibly contribute to $2.");
}

