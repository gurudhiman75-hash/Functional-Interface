function polishExplanationR5(question: StaV4Question, body: string): string {
  const parts = body.split("\n\n");
  const negative = question.queryPolarity === "NEGATIVE";
  const lead = EXPLANATION_LEADS[question.language][question.qlId][negative ? 1 : 0];
  return [lead, ...parts.slice(1)].join("\n\n");
}

export function generateStaV4Question(input: GenerateStaV4QuestionInput): StaV4Question {
  const r4 = generateStaV4R4Question(input);
  const localizedStatement = polishLocalizedR5(r4.statement, r4.language);
  const candidates = r4.candidates.map((candidate) => Object.freeze({
    ...candidate,
    text: polishLocalizedR5(candidate.text, r4.language),
  }));
  const localizedExplanation = polishLocalizedR5(r4.explanation, r4.language);
  const question = Object.freeze({
    ...r4,
    statement: localizedStatement,
    candidates: Object.freeze(candidates),
    explanation: polishExplanationR5(r4, localizedExplanation),
  }) as StaV4Question;
  assertStaV4QuestionIntegrity(question);
  return question;
}
