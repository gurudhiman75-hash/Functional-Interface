const HINDI_LEAD = "देखें कि बताए गए निर्देश को व्यवहार में पूरा करने के लिए कौन-सी मान्यताएँ वास्तव में आवश्यक हैं।\n\n";
const PUNJABI_LEAD = "ਵੇਖੋ ਕਿ ਦਿੱਤੀ ਹਦਾਇਤ ਨੂੰ ਅਮਲ ਵਿੱਚ ਪੂਰਾ ਕਰਨ ਲਈ ਕਿਹੜੀਆਂ ਮਾਨਤਾਵਾਂ ਅਸਲ ਵਿੱਚ ਲਾਜ਼ਮੀ ਹਨ।\n\n";

export function editorializeStaQl001LocalizedText(locale: StaLocalizedLocale, value: string): string {
  let result = value;
  const replacements = locale === "hi-IN" ? HINDI_REPLACEMENTS : PUNJABI_REPLACEMENTS;
  for (const [from, to] of replacements) result = result.replaceAll(from, to);
  return result;
}

function editorializeExplanation(locale: StaLocalizedLocale, value: string): string {
  const withoutLead = value.replace(locale === "hi-IN" ? HINDI_LEAD : PUNJABI_LEAD, "");
  return editorializeStaQl001LocalizedText(locale, withoutLead);
}

export function generateStaQl001LocalizedQuestionV2(seed: string, locale: StaLocalizedLocale): StaLocalizedQuestion {
  const source = generateStaQl001LocalizedQuestion(seed, locale);
  return {
    ...source,
    statement: editorializeStaQl001LocalizedText(locale, source.statement),
    candidates: source.candidates.map((candidate) => ({
      ...candidate,
      text: editorializeStaQl001LocalizedText(locale, candidate.text),
    })) as StaLocalizedQuestion["candidates"],
    options: source.options,
    explanation: editorializeExplanation(locale, source.explanation),
  };
}
