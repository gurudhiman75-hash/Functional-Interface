export const INT_CP001_ENGLISH_CLOSE_DISTRACTOR_RELEASE_ID = "INT-CP-001-EN-v5" as const;
export const INT_CP001_HINDI_CLOSE_DISTRACTOR_RELEASE_ID = "INT-CP-001-HI-v4" as const;
export const INT_CP001_PUNJABI_CLOSE_DISTRACTOR_RELEASE_ID = "INT-CP-001-PA-v4" as const;

export const INT_CP001_CLOSE_DISTRACTOR_STANDARD = "FOUR_TIER_GOLD_CLOSE_DISTRACTORS_V1" as const;
export const INT_CP001_CLOSE_DISTRACTOR_PATCH_ID = "INT-CP001-BOUNDED-NEAR-MISS-DISTRACTORS-V1" as const;

export type IntCp001CloseDistractorLanguage = "en" | "hi" | "pa";

export function getIntCp001CloseDistractorReleaseId(language: IntCp001CloseDistractorLanguage):
  | typeof INT_CP001_ENGLISH_CLOSE_DISTRACTOR_RELEASE_ID
  | typeof INT_CP001_HINDI_CLOSE_DISTRACTOR_RELEASE_ID
  | typeof INT_CP001_PUNJABI_CLOSE_DISTRACTOR_RELEASE_ID {
  if (language === "en") return INT_CP001_ENGLISH_CLOSE_DISTRACTOR_RELEASE_ID;
  return language === "hi"
    ? INT_CP001_HINDI_CLOSE_DISTRACTOR_RELEASE_ID
    : INT_CP001_PUNJABI_CLOSE_DISTRACTOR_RELEASE_ID;
}
