function replaceAll(value: string, pairs: readonly (readonly [string, string])[]) {
  let out = value;
  for (const [from, to] of pairs) out = out.split(from).join(to);
  return out;
}

function replaceShortEnglish(value: string, language: SapTranslationLanguage) {
  const map = language === "hi"
    ? new Map([
        ["it", "यह"], ["It", "यह"], ["at", "पर"], ["At", "पर"], ["on", "पर"],
        ["No", "कोई"], ["no", "कोई"], ["do", "करें"], ["Do", "करें"], ["up", "ऊपर"],
      ])
    : new Map([
        ["it", "ਇਹ"], ["It", "ਇਹ"], ["at", "ਤੇ"], ["At", "ਤੇ"], ["on", "ਉੱਤੇ"],
        ["No", "ਕੋਈ"], ["no", "ਕੋਈ"], ["do", "ਕਰੋ"], ["Do", "ਕਰੋ"], ["up", "ਉੱਪਰ"],
      ]);
  return value.replace(/\b(?:it|It|at|At|on|No|no|do|Do|up)\b/gu, (token) => map.get(token) ?? token);
}

