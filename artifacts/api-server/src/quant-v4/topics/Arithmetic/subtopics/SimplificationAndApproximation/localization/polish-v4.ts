function polishText(value: string, language: SapTranslationLanguage) {
  const math: string[] = [];
  let masked = value.replace(MATH, (fragment) => {
    const token = `§MATH${math.length}§`;
    math.push(fragment);
    return token;
  });
  masked = replaceAll(masked, language === "hi" ? HI_PHRASES : PA_PHRASES);
  masked = replaceShortEnglish(masked, language);
  masked = grammarPolish(masked, language);
  masked = masked.replace(/§MATH(\d+)§/gu, (_match, index) => math[Number(index)] ?? "");
  return masked.replace(/\s{2,}/gu, " ").replace(/\s+([,.;:?!।])/gu, "$1").trim();
}

export function applySapLocalizationPolishV4(pkg: any, language: SapTranslationLanguage) {
  const base = applySapLocalizationPolishV3(pkg, language);
  const options = Object.freeze(base.options.map((option: unknown) => polishText(String(option ?? ""), language)));
  const correctIndex = Number(base.correctIndex);
  const answer = options[correctIndex];
  const explanationLines = Object.freeze(
    (base.explanation?.lines ?? []).map((line: unknown) => polishText(String(line ?? ""), language)),
  );
  return Object.freeze({
    ...base,
    stem: polishText(String(base.stem ?? ""), language),
    options,
    correctIndex,
    answer,
    explanation: Object.freeze({ lines: explanationLines }),
    traceability: Object.freeze({
      ...(base.traceability ?? {}),
      localizationEditorialPolish: "SAP-HI-PA-EDITORIAL-POLISH-V4",
    }),
  });
}
