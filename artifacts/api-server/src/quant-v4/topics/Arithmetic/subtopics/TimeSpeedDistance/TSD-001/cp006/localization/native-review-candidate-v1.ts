function actors(source: EnglishRow, language: TsdCp006NativeLanguage) {
  return {
    a: cp006NativeActor(source.objectFamily, "A", language),
    b: cp006NativeActor(source.objectFamily, "B", language),
    c: cp006NativeActor(source.objectFamily, "C", language),
  } as const;
}

function directionPhrase(same: boolean, language: TsdCp006NativeLanguage): string {
  if (language === "hi") return same ? "एक ही दिशा में" : "विपरीत दिशाओं में";
  return same ? "ਇੱਕੋ ਦਿਸ਼ਾ ਵਿੱਚ" : "ਵਿਰੋਧੀ ਦਿਸ਼ਾਵਾਂ ਵਿੱਚ";
}

function ordinalFromSeed(source: EnglishRow): number {
  const value = Number(source.seed.split(":").at(-1));
  if (!Number.isInteger(value) || value < 1) throw new Error(`${source.seed}: invalid native ordinal`);
  return value - 1;
}

