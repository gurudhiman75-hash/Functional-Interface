function polishHindi(row: TsdCp005NativeReviewRowV1): string {
  let stem = row.presentation.stem;
  const a = cp005NativeActor(row.source.objectFamily, "A", "hi");
  const b = cp005NativeActor(row.source.objectFamily, "B", "hi");
  const sa = row.source.input.speedA ? cp005Speed(row.source.input.speedA) : "";
  const sb = row.source.input.speedB ? cp005Speed(row.source.input.speedB) : "";

  if (sa && sb) {
    stem = stem
      .replace(`A और B की गतियाँ क्रमशः ${sa} और ${sb} हैं।`, `${a} की गति ${sa} और ${b} की गति ${sb} है।`)
      .replace(`${a} ${sa} और ${b} ${sb} पर चलता है;`, `${a} की गति ${sa} और ${b} की गति ${sb} है;`)
      .replace(`${a} P से ${sa} और ${b} ${sb} की गति से Q की ओर चलता है।`, `${a} की गति ${sa} और ${b} की गति ${sb} है; दोनों P से Q की ओर चलते हैं।`)
      .replace(`${a} ${sa}, ${b} ${sb} पर है।`, `${a} की गति ${sa} और ${b} की गति ${sb} है।`)
      .replace(`${a} P से ${sa} और ${b} Q से ${sb} पर चलते हैं;`, `${a} P से ${sa} की गति से और ${b} Q से ${sb} की गति से चलते हैं;`)
      .replace(`${a} और ${b} विपरीत सिरों से ${sa} तथा ${sb} पर चलते हैं।`, `${a} और ${b} विपरीत सिरों से क्रमशः ${sa} और ${sb} की गति से चलते हैं।`)
      .replace(`${a} और ${b} P से साथ ${sa} और ${sb} पर चलते हैं।`, `${a} और ${b} P से साथ चलते हैं; उनकी गतियाँ क्रमशः ${sa} और ${sb} हैं।`)
      .replace(`दोनों P से Q की ओर ${sa} और ${sb} पर साथ चलते हैं;`, `दोनों P से Q की ओर साथ चलते हैं; उनकी गतियाँ क्रमशः ${sa} और ${sb} हैं;`);
  }

  stem = stem
    .replace(/(\d+(?:\.\d+)? km\/h) पर/g, "$1 की गति से")
    .replace(`${a} पहले Q पहुँचकर तुरंत लौटता है।`, `${a} के Q पहुँचते ही वापसी शुरू हो जाती है।`)
    .replace(`${a} Q से तुरंत लौटता है।`, `${a} के Q पहुँचते ही वापसी शुरू हो जाती है।`)
    .replace(`तेज ${a} Q पर पहुँचते ही वापस मुड़ता है।`, `${a} के Q पहुँचते ही तुरंत वापसी शुरू हो जाती है।`)
    .replace(`${a} Q छूते ही लौटता है।`, `${a} के Q पहुँचते ही वापसी शुरू हो जाती है।`)
    .replace(`${a} पहले Q पहुँचकर बिना रुके P की ओर लौटता है, जबकि ${b} Q की ओर चलता रहता है।`, `${a} के Q पहुँचते ही बिना ठहराव P की ओर वापसी शुरू हो जाती है, जबकि ${b} की Q की ओर यात्रा जारी रहती है।`)
    .replace(`${a} Q से तुरंत वापसी करता है।`, `${a} के Q पहुँचते ही वापसी शुरू हो जाती है।`)
    .replace(`${a} Q पहुँचते ही वापस मुड़ता है; ${b} आगे चलता रहता है।`, `${a} के Q पहुँचते ही वापसी शुरू हो जाती है; ${b} की Q की ओर यात्रा जारी रहती है।`)
    .replace(`तेज ${a} Q से तुरंत लौटता है।`, `${a} के Q पहुँचते ही तुरंत वापसी शुरू हो जाती है।`)
    .replace(`${a} वहीं से लौटता है।`, `Q पहुँचते ही ${a} की वापसी शुरू हो जाती है।`)
    .replace(`${a} Q पहुँचकर दिशा बदलता है।`, `${a} के Q पहुँचते ही वापसी शुरू हो जाती है।`)
    .replace(`तेज ${a} Q से तुरंत वापस आता है।`, `${a} के Q पहुँचते ही वापसी शुरू हो जाती है।`)
    .replace(`${a} लौटने पर ${b} से P से कितनी दूर मिलेगा?`, `${a} की वापसी के दौरान दोनों P से कितनी दूर मिलेंगे?`)
    .replace(`तेज ${a} Q से बिना रुके लौटता है।`, `${a} के Q पहुँचते ही बिना ठहराव वापसी शुरू हो जाती है।`)
    .replace(`${a} Q पर कुछ समय रुकता है, ${b} P से तुरंत लौटता है।`, `Q पर ${a} का कुछ समय ठहराव होता है, जबकि P पहुँचते ही ${b} की वापसी शुरू हो जाती है।`)
    .replace(`${a} Q पर रुककर लौटता है, ${b} बिना रुके लौटता है।`, `Q पर ${a} के ठहराव के बाद वापसी होती है, जबकि ${b} की वापसी में कोई ठहराव नहीं होता।`)
    .replace(`${a} Q पहुँचकर कुछ देर प्रतीक्षा करता है, जबकि ${b} P पर तुरंत दिशा बदलता है।`, `Q पर ${a} का कुछ देर ठहराव होता है, जबकि P पहुँचते ही ${b} की वापसी शुरू हो जाती है।`)
    .replace(`${a} Q पर ठहरता है और ${b} P से तुरंत वापस आता है।`, `Q पर ${a} का ठहराव होता है और P पहुँचते ही ${b} की वापसी शुरू हो जाती है।`)
    .replace(`Q पर केवल ${a} रुकता है।`, `Q पर केवल ${a} का ठहराव होता है।`)
    .replace(`${a} Q पर रुकता है, ${b} P पर नहीं रुकता।`, `Q पर ${a} का ठहराव होता है, जबकि P पर ${b} का कोई ठहराव नहीं होता।`)
    .replace("दिया गया समय-अंतर मुलाकात 1 और मुलाकात 2 के बीच है। ", "")
    .replace(/उनकी पहली दो मुलाकातों के बीच ([^.।]+) है।/u, "मुलाकात 1 और मुलाकात 2 के बीच $1 का अंतर है।");

  return stem.replace(/\s{2,}/g, " ").trim();
}

