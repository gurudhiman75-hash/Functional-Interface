function polishStem(text: string, language: TmwLocalizedLanguage): string {
  if (language === "hi") {
    return text
      .replace(/कुल उत्पादक क्षमता/g, "कुल काम करने की क्षमता")
      .replace(/बदली व्यवस्था/g, "नई स्थिति")
      .replace(/मूल व्यवस्था/g, "पुरानी स्थिति")
      .replace(/समायोजन/g, "बदलाव");
  }
  return text
    .replace(/ਕੁੱਲ ਉਤਪਾਦਕ ਸਮਰੱਥਾ/g, "ਕੁੱਲ ਕੰਮ ਕਰਨ ਦੀ ਸਮਰੱਥਾ")
    .replace(/ਬਦਲੀ ਵਿਵਸਥਾ/g, "ਨਵੀਂ ਸਥਿਤੀ")
    .replace(/ਮੂਲ ਵਿਵਸਥਾ/g, "ਪੁਰਾਣੀ ਸਥਿਤੀ")
    .replace(/ਸਮਾਯੋਜਨ/g, "ਬਦਲਾਅ");
}

export function remediateTmwCp006LocalizedQuestion(
  source: TmwCp006GeneratedQuestion,
  question: TmwLocalizedQuestion,
  language: TmwLocalizedLanguage,
): TmwLocalizedQuestion {
  const opening = OPENINGS[source.solveMode][language === "hi" ? 0 : 1];
  const misconceptionId = question.explanation.commonTrap.misconceptionId as Exclude<TmwCp006MisconceptionId, "CORRECT">;
  const trap = TRAPS[misconceptionId];

  return {
    ...question,
    stem: polishStem(question.stem, language),
    explanation: {
      ...question.explanation,
      opening,
      commonTrap: {
        ...question.explanation.commonTrap,
        explanation: trap[language === "hi" ? 0 : 1],
      },
      conclusion: conclusion(source.solveMode, question.solution.answerText, language),
    },
  };
}
