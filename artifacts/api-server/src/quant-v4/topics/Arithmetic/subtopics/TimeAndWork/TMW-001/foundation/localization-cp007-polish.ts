import type { TmwLocalizedLanguage } from "./localization-types";

export function polishTmwCp007LocalizedText(
  text: string,
  language: TmwLocalizedLanguage,
): string {
  if (language === "hi") {
    return text
      .replace(/1 दिन में/g, "एक दिन में")
      .replace(/([2-9]|\d{2,}) दिन में/g, "$1 दिनों में")
      .replace(/1 घंटे में/g, "एक घंटे में")
      .replace(/([2-9]|\d{2,}) घंटे में/g, "$1 घंटों में")
      .replace(/एक भारी मशीनें/g, "एक भारी मशीन")
      .replace(/एक मानक मशीनें/g, "एक मानक मशीन")
      .replace(/एक छोटी मशीनें/g, "एक छोटी मशीन")
      .replace(/एक तेज़ मशीनें/g, "एक तेज़ मशीन")
      .replace(/एक स्वचालित बोतल लाइनें/g, "एक स्वचालित बोतल लाइन")
      .replace(/एक अर्ध-स्वचालित बोतल लाइनें/g, "एक अर्ध-स्वचालित बोतल लाइन")
      .replace(/एक हाथ से चलने वाले स्टेशन/g, "एक हाथ से चलने वाला स्टेशन");
  }

  return text
    .replace(/1 ਦਿਨ ਵਿੱਚ/g, "ਇੱਕ ਦਿਨ ਵਿੱਚ")
    .replace(/([2-9]|\d{2,}) ਦਿਨ ਵਿੱਚ/g, "$1 ਦਿਨਾਂ ਵਿੱਚ")
    .replace(/1 ਘੰਟੇ ਵਿੱਚ/g, "ਇੱਕ ਘੰਟੇ ਵਿੱਚ")
    .replace(/([2-9]|\d{2,}) ਘੰਟੇ ਵਿੱਚ/g, "$1 ਘੰਟਿਆਂ ਵਿੱਚ")
    .replace(/ਇੱਕ ਭਾਰੀ ਮਸ਼ੀਨਾਂ/g, "ਇੱਕ ਭਾਰੀ ਮਸ਼ੀਨ")
    .replace(/ਇੱਕ ਮਿਆਰੀ ਮਸ਼ੀਨਾਂ/g, "ਇੱਕ ਮਿਆਰੀ ਮਸ਼ੀਨ")
    .replace(/ਇੱਕ ਛੋਟੀਆਂ ਮਸ਼ੀਨਾਂ/g, "ਇੱਕ ਛੋਟੀ ਮਸ਼ੀਨ")
    .replace(/ਇੱਕ ਤੇਜ਼ ਮਸ਼ੀਨਾਂ/g, "ਇੱਕ ਤੇਜ਼ ਮਸ਼ੀਨ")
    .replace(/ਇੱਕ ਆਟੋਮੈਟਿਕ ਬੋਤਲ ਲਾਈਨਾਂ/g, "ਇੱਕ ਆਟੋਮੈਟਿਕ ਬੋਤਲ ਲਾਈਨ")
    .replace(/ਇੱਕ ਅਰਧ-ਆਟੋਮੈਟਿਕ ਬੋਤਲ ਲਾਈਨਾਂ/g, "ਇੱਕ ਅਰਧ-ਆਟੋਮੈਟਿਕ ਬੋਤਲ ਲਾਈਨ")
    .replace(/ਇੱਕ ਹੱਥ ਨਾਲ ਚੱਲਣ ਵਾਲੇ ਸਟੇਸ਼ਨ/g, "ਇੱਕ ਹੱਥ ਨਾਲ ਚੱਲਣ ਵਾਲਾ ਸਟੇਸ਼ਨ");
}
