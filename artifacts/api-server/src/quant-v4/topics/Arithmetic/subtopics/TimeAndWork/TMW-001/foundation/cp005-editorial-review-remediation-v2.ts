function conclusion(
  question: TmwLocalizedQuestion<TmwLocalizedValue>,
  source: TmwCp005GeneratedQuestion,
  language: TmwLocalizedLanguage,
): string {
  const answer = question.solution.answerText;
  const B = cp005Actor(source.parameters, language, "actorB");
  switch (source.solveMode) {
    case "findTerminalAgent":
      return copy(language, `अतः काम ${answer} की बारी में पूरा होगा।`, `ਇਸ ਲਈ ਕੰਮ ${answer} ਦੀ ਵਾਰੀ ਵਿੱਚ ਪੂਰਾ ਹੋਵੇਗਾ।`);
    case "findStartingAgentFromCompletionCondition":
      return copy(language, `अतः दिया कुल समय और अंतिम बारी केवल ${answer} से शुरुआत करने पर मेल खाते हैं।`, `ਇਸ ਲਈ ਦਿੱਤਾ ਕੁੱਲ ਸਮਾਂ ਅਤੇ ਆਖ਼ਰੀ ਵਾਰੀ ਸਿਰਫ਼ ${answer} ਤੋਂ ਸ਼ੁਰੂ ਕਰਨ ਉੱਤੇ ਮਿਲਦੇ ਹਨ।`);
    case "findUnknownRateFromAlternatingCompletion":
      return copy(language, `अतः ${B} की दैनिक दर ${answer} है।`, `ਇਸ ਲਈ ${B} ਦੀ ਰੋਜ਼ਾਨਾ ਦਰ ${answer} ਹੈ।`);
    case "findUnknownTimeFromAlternatingCompletion":
      return copy(language, `अतः ${B} अकेले पूरा काम ${answer} में करेगा।`, `ਇਸ ਲਈ ${B} ਇਕੱਲਾ ਸਾਰਾ ਕੰਮ ${answer} ਵਿੱਚ ਕਰੇਗਾ।`);
    case "findCycleCountToReachSpecifiedFraction":
      return copy(language, `अतः लक्षित भाग तक पहुँचने के लिए ${answer} चाहिए।`, `ਇਸ ਲਈ ਟੀਚੇ ਵਾਲੇ ਹਿੱਸੇ ਤੱਕ ਪਹੁੰਚਣ ਲਈ ${answer} ਚਾਹੀਦੇ ਹਨ।`);
    case "findRequiredCycleRateForDeadline":
      return copy(language, `अतः जब भी ${B} की बारी हो, उसकी आवश्यक दैनिक दर ${answer} होनी चाहिए।`, `ਇਸ ਲਈ ਜਦੋਂ ਵੀ ${B} ਦੀ ਵਾਰੀ ਹੋਵੇ, ਉਸ ਦੀ ਲੋੜੀਂਦੀ ਰੋਜ਼ਾਨਾ ਦਰ ${answer} ਹੋਣੀ ਚਾਹੀਦੀ ਹੈ।`);
    default:
      return naturalize(question.explanation.conclusion, language);
  }
}

export function applyTmwCp005EditorialReviewRemediation(
  question: TmwLocalizedQuestion<TmwLocalizedValue>,
  source: TmwCp005GeneratedQuestion,
  language: TmwLocalizedLanguage,
): TmwLocalizedQuestion<TmwLocalizedValue> {
  const updated: TmwLocalizedQuestion<TmwLocalizedValue> = {
    ...question,
    stem: naturalizeStem(question.stem, source, language),
    explanation: {
      ...question.explanation,
      opening: opening(source, language),
      shortcut: {
        title: naturalize(question.explanation.shortcut.title, language),
        steps: question.explanation.shortcut.steps.map((step) => naturalize(step, language)),
      },
      commonTrap: {
        ...question.explanation.commonTrap,
        explanation: trap(
          question.explanation.commonTrap.misconceptionId,
          language,
          question.explanation.commonTrap.explanation,
        ),
      },
      conclusion: question.explanation.conclusion,
    },
  };
  return {
    ...updated,
    explanation: {
      ...updated.explanation,
      conclusion: conclusion(updated, source, language),
    },
  };
}
