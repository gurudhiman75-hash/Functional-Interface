  if (language === "hi") {
    return value
      .replaceAll("अंतिम सक्रिय बारी", "आखिरी बारी")
      .replaceAll("अगली सक्रिय दर", "अगली बारी की दर")
      .replaceAll("एक पूरे चक्र की अवस्था", "एक पूरे चक्र का हिसाब")
      .replaceAll("उसी अवस्था से", "उसी हिसाब से")
      .replaceAll("अज्ञात सक्रिय समय", "अज्ञात सदस्य के काम करने के कुल समय")
      .replaceAll("अज्ञात बारी की कुल सक्रिय अवधि", "अज्ञात सदस्य के काम करने का कुल समय")
      .replaceAll("शुद्ध चक्र-काम", "एक चक्र में हुआ वास्तविक काम")
      .replaceAll("सकारात्मक काम", "काम करने वालों का काम")
      .replaceAll("सकारात्मक दिनों", "काम करने वाले दिनों")
      .replaceAll("सीमा-समय", "कुल समय")
      .replaceAll("हर खंड की दर × अवधि जोड़कर", "हर खंड में दर × समय जोड़कर");
  }
  return value
    .replaceAll("ਆਖ਼ਰੀ ਸਰਗਰਮ ਵਾਰੀ", "ਆਖ਼ਰੀ ਵਾਰੀ")
    .replaceAll("ਅਗਲੀ ਸਰਗਰਮ ਦਰ", "ਅਗਲੀ ਵਾਰੀ ਦੀ ਦਰ")
    .replaceAll("ਇੱਕ ਪੂਰੇ ਚੱਕਰ ਦੀ ਸਥਿਤੀ", "ਇੱਕ ਪੂਰੇ ਚੱਕਰ ਦਾ ਹਿਸਾਬ")
    .replaceAll("ਉਸੇ ਸਥਿਤੀ ਤੋਂ", "ਉਸੇ ਹਿਸਾਬ ਨਾਲ")
    .replaceAll("ਅਣਜਾਣ ਸਰਗਰਮ ਸਮੇਂ", "ਅਣਜਾਣ ਮੈਂਬਰ ਦੇ ਕੰਮ ਕਰਨ ਦੇ ਕੁੱਲ ਸਮੇਂ")
    .replaceAll("ਅਣਜਾਣ ਵਾਰੀ ਦੀ ਕੁੱਲ ਸਰਗਰਮ ਮਿਆਦ", "ਅਣਜਾਣ ਮੈਂਬਰ ਦੇ ਕੰਮ ਕਰਨ ਦਾ ਕੁੱਲ ਸਮਾਂ")
    .replaceAll("ਸ਼ੁੱਧ ਚੱਕਰ-ਕੰਮ", "ਇੱਕ ਚੱਕਰ ਵਿੱਚ ਹੋਇਆ ਅਸਲ ਕੰਮ")
    .replaceAll("ਸਕਾਰਾਤਮਕ ਕੰਮ", "ਕੰਮ ਕਰਨ ਵਾਲਿਆਂ ਦਾ ਕੰਮ")
    .replaceAll("ਸਕਾਰਾਤਮਕ ਦਿਨਾਂ", "ਕੰਮ ਕਰਨ ਵਾਲੇ ਦਿਨਾਂ")
    .replaceAll("ਹੱਦ-ਸਮਾਂ", "ਕੁੱਲ ਸਮਾਂ")
    .replaceAll("ਹਰ ਖੰਡ ਦੀ ਦਰ × ਮਿਆਦ ਜੋੜ ਕੇ", "ਹਰ ਖੰਡ ਵਿੱਚ ਦਰ × ਸਮਾਂ ਜੋੜ ਕੇ");
