export function naturalizeTmw001LocalizedExplanation<T extends ExplanationQuestion>(
  question: T,
  qlId: string,
  language: TmwLocalizedLanguage,
): T {
  const copy = SHORTCUTS[qlId];
  if (!copy) return question;
  const step = copy[language].replaceAll(
    "{answer}",
    question.solution.answerText,
  );
  return {
    ...question,
    explanation: {
      ...question.explanation,
      shortcut: {
        ...question.explanation.shortcut,
        steps: [step],
      },
    },
  };
}
