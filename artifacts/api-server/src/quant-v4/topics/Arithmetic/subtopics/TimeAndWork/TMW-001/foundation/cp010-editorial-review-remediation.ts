function conclusion(
  source: TmwCp010GeneratedQuestion,
  answerText: string,
  language: TmwLocalizedLanguage,
): string {
  switch (source.solution.answerType) {
    case "TIME": return pair(language, `अतः कुल आवश्यक समय ${answerText} है।`, `ਇਸ ਲਈ ਕੁੱਲ ਲੋੜੀਂਦਾ ਸਮਾਂ ${answerText} ਹੈ।`);
    case "LEVEL": return pair(language, `अतः निर्धारित समय के बाद टंकी ${answerText} होगी।`, `ਇਸ ਲਈ ਨਿਰਧਾਰਤ ਸਮੇਂ ਤੋਂ ਬਾਅਦ ਟੈਂਕੀ ${answerText} ਹੋਵੇਗੀ।`);
    case "FLOW_RATE": return pair(language, `अतः अंतिम चरण की आवश्यक भराव दर ${answerText} है।`, `ਇਸ ਲਈ ਅੰਤਿਮ ਪੜਾਅ ਦੀ ਲੋੜੀਂਦੀ ਭਰਨ ਦਰ ${answerText} ਹੈ।`);
    case "CAPACITY": return pair(language, `अतः टंकी की कुल क्षमता ${answerText} है।`, `ਇਸ ਲਈ ਟੈਂਕੀ ਦੀ ਕੁੱਲ ਸਮਰੱਥਾ ${answerText} ਹੈ।`);
    case "COUNT": return pair(language, `अतः उत्तर ${answerText} है।`, `ਇਸ ਲਈ ਉੱਤਰ ${answerText} ਹੈ।`);
    case "SEGMENT": return pair(language, `अतः लक्ष्य जिस हिस्से में पूरा होता है, वह ${answerText} है।`, `ਇਸ ਲਈ ਟੀਚਾ ਜਿਸ ਹਿੱਸੇ ਵਿੱਚ ਪੂਰਾ ਹੁੰਦਾ ਹੈ, ਉਹ ${answerText} ਹੈ।`);
  }
}

export function remediateTmwCp010LocalizedEditorial(
  source: TmwCp010GeneratedQuestion,
  fields: TmwCp010LocalizedEditorialFields,
  answerText: string,
  language: TmwLocalizedLanguage,
): TmwCp010LocalizedEditorialFields {
  const misconceptionId = source.explanation.commonTrap.misconceptionId as Exclude<TmwCp010MisconceptionId, "CORRECT">;
  return {
    stem: clean(fields.stem, language),
    opening: OPENINGS[source.solveMode][language === "hi" ? 0 : 1],
    givens: fields.givens.map((text) => clean(text, language)),
    workedSteps: fields.workedSteps.map((text) => clean(text, language)),
    shortcut: shortcut(source.solveMode, answerText, language),
    trapExplanation: trap(misconceptionId, language),
    conclusion: conclusion(source, answerText, language),
  };
}
