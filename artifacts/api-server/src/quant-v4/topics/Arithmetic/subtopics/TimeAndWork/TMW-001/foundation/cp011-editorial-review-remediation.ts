function conclusion(answerType: TmwCp011AnswerType, answerText: string, language: TmwLocalizedLanguage): string {
  if (language === "hi") {
    switch (answerType) {
      case "TIME": return `अतः लक्ष्य पूरा होने का सही समय ${answerText} है।`;
      case "DAY_INDEX": return `अतः दर बदलने का सही स्थान ${answerText} है।`;
      case "RATE": return `अतः आवश्यक दैनिक दर ${answerText} है।`;
      case "RATE_CHANGE": return `अतः दैनिक दर में सही बदलाव ${answerText} है।`;
      case "MULTIPLIER": return `अतः दैनिक दर का सही गुणक ${answerText} है।`;
      case "OUTPUT": return `अतः निर्धारित अवधि का सही कुल उत्पादन ${answerText} है।`;
    }
  }
  switch (answerType) {
    case "TIME": return `ਇਸ ਲਈ ਟੀਚਾ ਪੂਰਾ ਹੋਣ ਦਾ ਠੀਕ ਸਮਾਂ ${answerText} ਹੈ।`;
    case "DAY_INDEX": return `ਇਸ ਲਈ ਦਰ ਬਦਲਣ ਦੀ ਠੀਕ ਥਾਂ ${answerText} ਹੈ।`;
    case "RATE": return `ਇਸ ਲਈ ਲੋੜੀਂਦੀ ਰੋਜ਼ਾਨਾ ਦਰ ${answerText} ਹੈ।`;
    case "RATE_CHANGE": return `ਇਸ ਲਈ ਰੋਜ਼ਾਨਾ ਦਰ ਵਿੱਚ ਠੀਕ ਬਦਲਾਅ ${answerText} ਹੈ।`;
    case "MULTIPLIER": return `ਇਸ ਲਈ ਰੋਜ਼ਾਨਾ ਦਰ ਦਾ ਠੀਕ ਗੁਣਕ ${answerText} ਹੈ।`;
    case "OUTPUT": return `ਇਸ ਲਈ ਨਿਰਧਾਰਤ ਸਮੇਂ ਦਾ ਠੀਕ ਕੁੱਲ ਉਤਪਾਦਨ ${answerText} ਹੈ।`;
  }
}

export function remediateTmwCp011LocalizedQuestion(
  source: TmwCp011GeneratedQuestion,
  question: TmwCp011LocalizedQuestion,
): TmwCp011LocalizedQuestion {
  const language = question.language;
  const method = METHODS[source.solveMode];
  const answerText = clean(question.solution.answerText, language);
  const options = question.options.map((value) => clean(value, language));
  const optionAudit = question.optionAudit.map((option, index) => ({
    ...option,
    text: options[index] ?? clean(option.text, language),
  }));
  const trapIndex = source.optionAudit.findIndex(
    (option) => option.misconceptionId === question.explanation.commonTrap.misconceptionId,
  );
  const safeTrapIndex = trapIndex >= 0 ? trapIndex : 0;
  const trapOption = options[safeTrapIndex] ?? question.explanation.commonTrap.optionText;
  const trapReason = TRAP_REASONS[question.explanation.commonTrap.misconceptionId];
  const workedSteps = [
    pick(method.workedLead, language),
    ...question.explanation.steps.slice(1).map((value) => clean(value, language)),
  ];

  return {
    ...question,
    stem: clean(question.stem, language),
    solution: { ...question.solution, answerText },
    options,
    optionAudit,
    explanation: {
      opening: pick(method.opening, language),
      formula: question.explanation.formula,
      givens: question.explanation.givens.map((value) => clean(value, language)),
      steps: workedSteps,
      shortcut: {
        title: pick(method.title, language),
        steps: method.shortcut.map((value) => pick(value, language)),
      },
      commonTrap: {
        ...question.explanation.commonTrap,
        optionText: trapOption,
        explanation: language === "hi"
          ? `${question.explanation.commonTrap.optionLabel} (${trapOption}) गलत है, क्योंकि ${pick(trapReason, language)}`
          : `${question.explanation.commonTrap.optionLabel} (${trapOption}) ਗਲਤ ਹੈ, ਕਿਉਂਕਿ ${pick(trapReason, language)}`,
      },
      conclusion: conclusion(source.solution.answerType, answerText, language),
    },
  };
}
