function clean(text: string, language: TmwLocalizedLanguage): string {
  if (language === "hi") {
    return text
      .replace(/10-सेकंड तरीका/g, "तेज़ जाँच")
      .replace(/दिनक्रम/g, "दिनों का दिया क्रम")
      .replace(/दो अलग चरणों/g, "बदलाव से पहले और बाद के दो चरणों")
      .replace(/शुद्ध काम/g, "उपयोगी काम में से घटाने वाला काम निकालने के बाद बचा काम")
      .replace(/चिह्न सहित/g, "बढ़ने और घटने की दिशा के साथ")
      .replace(/अवधियाँ/g, "समय-अंतराल")
      .replace(/सही नियम लिखें/g, "प्रश्न के अनुसार संबंध लिखें")
      .replace(/पाइपें चलती है(?:ं+)*/g, "पाइपें काम करती हैं");
  }
  return text
    .replace(/10-ਸਕਿੰਟ ਤਰੀਕਾ/g, "ਤੇਜ਼ ਜਾਂਚ")
    .replace(/ਦਿਨਕ੍ਰਮ/g, "ਦਿਨਾਂ ਦਾ ਦਿੱਤਾ ਕ੍ਰਮ")
    .replace(/ਦੋ ਵੱਖਰੇ ਪੜਾਅਾਂ/g, "ਬਦਲਾਅ ਤੋਂ ਪਹਿਲਾਂ ਅਤੇ ਬਾਅਦ ਦੇ ਦੋ ਪੜਾਵਾਂ")
    .replace(/ਸ਼ੁੱਧ ਕੰਮ/g, "ਲਾਭਕਾਰੀ ਕੰਮ ਵਿੱਚੋਂ ਘਟਾਉਣ ਵਾਲਾ ਕੰਮ ਕੱਢਣ ਤੋਂ ਬਾਅਦ ਬਚਿਆ ਕੰਮ")
    .replace(/ਚਿੰਨ੍ਹ ਸਮੇਤ/g, "ਵਧਣ ਅਤੇ ਘਟਣ ਦੀ ਦਿਸ਼ਾ ਸਮੇਤ")
    .replace(/ਮਿਆਦਾਂ/g, "ਸਮੇਂ ਦੇ ਹਿੱਸੇ")
    .replace(/ਠੀਕ ਨਿਯਮ ਲਿਖੋ/g, "ਸਵਾਲ ਅਨੁਸਾਰ ਸੰਬੰਧ ਲਿਖੋ");
}

