function naturalizeTrap(
  qlId: string,
  text: string,
  language: TmwLocalizedLanguage,
): string {
  if (qlId === "TMW-QL-193") {
    return language === "hi"
      ? text.replace("AP के कुल", "समान अंतर वाली दर-श्रृंखला के कुल")
      : text.replace("AP ਦੇ ਕੁੱਲ", "ਇੱਕੋ ਫਰਕ ਵਾਲੀ ਦਰ-ਲੜੀ ਦੇ ਕੁੱਲ");
  }
  if (qlId === "TMW-QL-195") {
    return language === "hi"
      ? text.replace(
          "n दिनों में दर केवल n−1 बार बदलती है",
          "दिए दिनों में दर, दिनों की संख्या से एक कम बार बदलती है",
        )
      : text.replace(
          "n ਦਿਨਾਂ ਵਿੱਚ ਦਰ ਕੇਵਲ n−1 ਵਾਰ ਬਦਲਦੀ ਹੈ",
          "ਦਿੱਤੇ ਦਿਨਾਂ ਵਿੱਚ ਦਰ, ਦਿਨਾਂ ਦੀ ਗਿਣਤੀ ਤੋਂ ਇੱਕ ਘੱਟ ਵਾਰ ਬਦਲਦੀ ਹੈ",
        );
  }
  if (qlId === "TMW-QL-200") {
    return language === "hi"
      ? text.replace(
          "गुणक r को प्रतिदिन जोड़ने वाली निश्चित मात्रा समझ लिया गया; यहाँ दर को r से गुणा करना है",
          "दैनिक गुणक को प्रतिदिन जोड़ने वाली निश्चित मात्रा समझ लिया गया; यहाँ हर नई दर पिछली दर को उस गुणक से गुणा करके बनती है",
        )
      : text.replace(
          "ਗੁਣਕ r ਨੂੰ ਹਰ ਦਿਨ ਜੋੜੀ ਜਾਣ ਵਾਲੀ ਨਿਰਧਾਰਤ ਮਾਤਰਾ ਸਮਝ ਲਿਆ ਗਿਆ; ਇੱਥੇ ਦਰ ਨੂੰ r ਨਾਲ ਗੁਣਾ ਕਰਨਾ ਹੈ",
          "ਰੋਜ਼ਾਨਾ ਗੁਣਕ ਨੂੰ ਹਰ ਦਿਨ ਜੋੜੀ ਜਾਣ ਵਾਲੀ ਨਿਰਧਾਰਤ ਮਾਤਰਾ ਸਮਝ ਲਿਆ ਗਿਆ; ਇੱਥੇ ਹਰ ਨਵੀਂ ਦਰ ਪਿਛਲੀ ਦਰ ਨੂੰ ਉਸ ਗੁਣਕ ਨਾਲ ਗੁਣਾ ਕਰਕੇ ਬਣਦੀ ਹੈ",
        );
  }
  return text;
}

export function remediateTmwCp011TeachingLanguage(
  question: TmwCp011LocalizedQuestion,
  qlId: string,
): TmwCp011LocalizedQuestion {
  const copy = TEACHING_COPY[qlId];
  const language = question.language;
  const currentExplanation = question.explanation;
  const shortcut = copy?.shortcut
    ? {
        ...currentExplanation.shortcut,
        steps: copy.shortcut.map((step) => pick(step, language)),
      }
    : currentExplanation.shortcut;
  const steps = copy?.workedLead
    ? [pick(copy.workedLead, language), ...currentExplanation.steps.slice(1)]
    : currentExplanation.steps;
  const trapExplanation = naturalizeTrap(
    qlId,
    currentExplanation.commonTrap.explanation,
    language,
  );

  if (!copy && trapExplanation === currentExplanation.commonTrap.explanation) {
    return question;
  }

  return {
    ...question,
    explanation: {
      ...currentExplanation,
      opening: copy?.opening
        ? pick(copy.opening, language)
        : currentExplanation.opening,
      steps,
      shortcut,
      commonTrap: {
        ...currentExplanation.commonTrap,
        explanation: trapExplanation,
      },
    },
  };
}
