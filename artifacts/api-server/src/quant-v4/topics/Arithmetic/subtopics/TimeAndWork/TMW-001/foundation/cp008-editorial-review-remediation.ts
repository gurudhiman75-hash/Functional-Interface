export function remediateTmwCp008LocalizedEditorial(
  source: TmwCp008GeneratedQuestion,
  fields: TmwCp008LocalizedEditorialFields,
  answerText: string,
  language: TmwLocalizedLanguage,
): TmwCp008LocalizedEditorialFields {
  const misconceptionId = source.explanation.commonTrap.misconceptionId as Exclude<TmwCp008MisconceptionId, "CORRECT">;
  return {
    stem: clean(fields.stem, language),
    opening: OPENINGS[source.solveMode][language === "hi" ? 0 : 1],
    givens: fields.givens.map((text) => clean(text, language)),
    workedSteps: fields.workedSteps.map((text) => clean(text, language)),
    shortcut: shortcut(source.solveMode, answerText, language),
    trapExplanation: trap(misconceptionId, language),
    conclusion: conclusion(source.solveMode, answerText, language),
  };
}
