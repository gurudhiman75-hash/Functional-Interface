import type { TmwLocalizedLanguage } from "./localization-types";

function normalizeMixedFractions(text: string): string {
  return text.replace(
    /(^|[^\d])(-?\d+)\s+(\d+)\/(\d+)(?!\d)/g,
    (_match, prefix: string, whole: string, numerator: string, denominator: string) =>
      `${prefix}\\(${whole}\\frac{${numerator}}{${denominator}}\\)`,
  );
}

function polishHindi(text: string): string {
  return text
    .replace(/_\{hour\}/g, "_{घंटा}")
    .replace(/_\{minute\}/g, "_{मिनट}")
    .replace(/_\{full\}/g, "_{पूर्ण}")
    .replace(/_\{empty\}/g, "_{खाली}")
    .replace(/((?:[2-9]|\d{2,})) घंटे में/g, "$1 घंटों में")
    .replace(/((?:[2-9]|\d{2,})) घंटे के भीतर/g, "$1 घंटों के भीतर")
    .replace(/पाइपें एक साथ खोलने/g, "पाइपों को एक साथ खोलने")
    .replace(/सभी भरने वाली पाइपें एक साथ खोलने पर/g, "सभी भरने वाली पाइपों को एक साथ खोलने पर")
    .replace(/सभी पाइपें लगातार खुली रहती हैं/g, "सभी पाइप लगातार खुले रहते हैं")
    .replace(/सभी पाइपें एक साथ खोलने पर/g, "सभी पाइप एक साथ खोलने पर")
    .replace(/सभी पाइपें मिलकर/g, "सभी पाइप मिलकर")
    .replace(/सभी पाइपें ([^।]+) तक खुली रहें/g, "सभी पाइप $1 तक खुले रहें")
    .replace(/सभी पाइपें ([^।]+) तक खुली रहती हैं/g, "सभी पाइप $1 तक खुले रहते हैं")
    .replace(/ज्ञात पाइपें:/g, "ज्ञात पाइप:")
    .replace(/पाइप अभिलेख:/g, "पाइपों का विवरण:")
    .replace(/हस्ताक्षरित दर/g, "चिह्न सहित दर")
    .replace(/हस्ताक्षरित शुद्ध दर/g, "चिह्न सहित शुद्ध दर")
    .replace(/हस्ताक्षरित स्तर अद्यतन/g, "चिह्न सहित स्तर परिवर्तन")
    .replace(/परिमाण/g, "मान")
    .replace(/लक्ष्य: टंकी को पूरी भरने का समय।/g, "लक्ष्य: टंकी के पूरी तरह भरने का समय।")
    .replace(/लक्ष्य: टंकी को पूरी खाली का समय।/g, "लक्ष्य: टंकी के पूरी तरह खाली होने का समय।")
    .replace(/टंकी पूरी भरने में/g, "टंकी के पूरी तरह भरने में")
    .replace(/टंकी पूरी खाली होने में/g, "टंकी के पूरी तरह खाली होने में")
    .replace(/में पूरी तरह खाली देती हैं/g, "में पूरी तरह खाली कर देते हैं")
    .replace(/में पूरी तरह भर देती हैं/g, "में पूरी तरह भर देते हैं")
    .replace(/पूरी तरह खाली जाती है/g, "पूरी तरह खाली हो जाती है")
    .replace(/पूरी तरह खाली जाएगी/g, "पूरी तरह खाली हो जाएगी")
    .replace(/रिसाव ([A-Z]) भी लगातार काम करती है/g, "रिसाव $1 भी लगातार काम करता है")
    .replace(/रिसाव ([A-Z]) अकेले पूरी भरी टंकी खाली करने में कितना समय लेगी\?/g, "रिसाव $1 अकेला पूरी भरी टंकी को खाली करने में कितना समय लेगा?")
    .replace(/अज्ञात: रिसाव ([A-Z]) का अकेले काम करने का समय।/g, "अज्ञात: रिसाव $1 द्वारा अकेले टंकी खाली करने में लगने वाला समय।")
    .replace(/अज्ञात: भरने वाली पाइप ([A-Z]) का अकेले काम करने का समय।/g, "अज्ञात: भरने वाली पाइप $1 द्वारा अकेले टंकी भरने का समय।")
    .replace(/टंकी पूरी तरह भर होने में/g, "टंकी के पूरी तरह भरने में")
    .replace(/लक्ष्य सीमा: पूरी तरह भर।/g, "लक्ष्य सीमा: पूर्ण भराव।")
    .replace(/जाँची जा रही सीमा: पूरी तरह भर।/g, "जाँची जा रही सीमा: पूर्ण भराव।")
    .replace(/पानी के स्तर के साथ क्या होगा\?/g, "पानी का स्तर बढ़ेगा, घटेगा या स्थिर रहेगा?")
    .replace(/कितना समय लेंगी\?/g, "कितना समय लगेगा?")
    .replace(/tank per (?:घंटा|घंटे)/g, "टंकी प्रति घंटा")
    .replace(/litres\/घंटा/g, "लीटर/घंटा")
    .replace(/litres\/मिनट/g, "लीटर/मिनट")
    .replace(/litres/g, "लीटर")
    .replace(/required level change/g, "आवश्यक स्तर परिवर्तन")
    .replace(/level change needed/g, "आवश्यक स्तर परिवर्तन")
    .replace(/lost efficiency/g, "दक्षता की कमी")
    .replace(/blockage/g, "अवरोध")
    .replace(/tank fills/g, "टंकी भरती है")
    .replace(/tank empties/g, "टंकी खाली होती है")
    .replace(/level is unchanged/g, "पानी का स्तर अपरिवर्तित रहता है")
    .replace(/boundary is not reached within the window/g, "उपलब्ध समय में सीमा तक नहीं पहुँचती");
}

function polishPunjabi(text: string): string {
  return text
    .replace(/_\{hour\}/g, "_{ਘੰਟਾ}")
    .replace(/_\{minute\}/g, "_{ਮਿੰਟ}")
    .replace(/_\{full\}/g, "_{ਪੂਰਾ}")
    .replace(/_\{empty\}/g, "_{ਖਾਲੀ}")
    .replace(/अकेले/g, "ਇਕੱਲੀ")
    .replace(/में टंकी भरती है/g, "ਵਿੱਚ ਟੈਂਕੀ ਭਰਦੀ ਹੈ")
    .replace(/में टंकी खाली करती है/g, "ਵਿੱਚ ਟੈਂਕੀ ਖਾਲੀ ਕਰਦੀ ਹੈ")
    .replace(/टंकी/g, "ਟੈਂਕੀ")
    .replace(/भरती है/g, "ਭਰਦੀ ਹੈ")
    .replace(/खाली करती है/g, "ਖਾਲੀ ਕਰਦੀ ਹੈ")
    .replace(/में/g, "ਵਿੱਚ")
    .replace(/((?:[2-9]|\d{2,})) ਘੰਟੇ ਵਿੱਚ/g, "$1 ਘੰਟਿਆਂ ਵਿੱਚ")
    .replace(/((?:[2-9]|\d{2,})) ਘੰਟੇ ਦੇ ਅੰਦਰ/g, "$1 ਘੰਟਿਆਂ ਦੇ ਅੰਦਰ")
    .replace(/ਪਤਾ ਪਾਈਪਾਂ:/g, "ਪਤਾ ਪਾਈਪ:")
    .replace(/ਪਾਈਪ ਰਿਕਾਰਡ:/g, "ਪਾਈਪਾਂ ਦਾ ਵੇਰਵਾ:")
    .replace(/ਚਿੰਨ੍ਹਿਤ ਸ਼ੁੱਧ ਦਰ/g, "ਚਿੰਨ੍ਹ ਸਮੇਤ ਸ਼ੁੱਧ ਦਰ")
    .replace(/ਚਿੰਨ੍ਹਿਤ ਦਰ/g, "ਚਿੰਨ੍ਹ ਸਮੇਤ ਦਰ")
    .replace(/ਚਿੰਨ੍ਹਿਤ ਪੱਧਰ ਅਪਡੇਟ/g, "ਚਿੰਨ੍ਹ ਸਮੇਤ ਪੱਧਰ ਬਦਲਾਅ")
    .replace(/ਪਰਿਮਾਣ/g, "ਮਾਨ")
    .replace(/ਟੀਚਾ: ਟੈਂਕੀ ਨੂੰ ਪੂਰੀ ਭਰਨ ਦਾ ਸਮਾਂ।/g, "ਟੀਚਾ: ਟੈਂਕੀ ਦੇ ਪੂਰੀ ਤਰ੍ਹਾਂ ਭਰਨ ਦਾ ਸਮਾਂ।")
    .replace(/ਟੀਚਾ: ਟੈਂਕੀ ਨੂੰ ਪੂਰੀ ਖਾਲੀ ਦਾ ਸਮਾਂ।/g, "ਟੀਚਾ: ਟੈਂਕੀ ਦੇ ਪੂਰੀ ਤਰ੍ਹਾਂ ਖਾਲੀ ਹੋਣ ਦਾ ਸਮਾਂ।")
    .replace(/ਟੈਂਕੀ ਪੂਰੀ ਭਰਨ ਵਿੱਚ/g, "ਟੈਂਕੀ ਦੇ ਪੂਰੀ ਤਰ੍ਹਾਂ ਭਰਨ ਵਿੱਚ")
    .replace(/ਟੈਂਕੀ ਪੂਰੀ ਖਾਲੀ ਹੋਣ ਵਿੱਚ/g, "ਟੈਂਕੀ ਦੇ ਪੂਰੀ ਤਰ੍ਹਾਂ ਖਾਲੀ ਹੋਣ ਵਿੱਚ")
    .replace(/ਵਿੱਚ ਪੂਰੀ ਤਰ੍ਹਾਂ ਖਾਲੀ ਦਿੰਦੀਆਂ ਹਨ/g, "ਵਿੱਚ ਪੂਰੀ ਤਰ੍ਹਾਂ ਖਾਲੀ ਕਰ ਦਿੰਦੀਆਂ ਹਨ")
    .replace(/ਵਿੱਚ ਪੂਰੀ ਤਰ੍ਹਾਂ ਭਰ ਦਿੰਦੀਆਂ ਹਨ/g, "ਵਿੱਚ ਪੂਰੀ ਤਰ੍ਹਾਂ ਭਰ ਦਿੰਦੀਆਂ ਹਨ")
    .replace(/ਪੂਰੀ ਤਰ੍ਹਾਂ ਖਾਲੀ ਜਾਂਦੀ ਹੈ/g, "ਪੂਰੀ ਤਰ੍ਹਾਂ ਖਾਲੀ ਹੋ ਜਾਂਦੀ ਹੈ")
    .replace(/ਪੂਰੀ ਤਰ੍ਹਾਂ ਖਾਲੀ ਜਾਵੇਗੀ/g, "ਪੂਰੀ ਤਰ੍ਹਾਂ ਖਾਲੀ ਹੋ ਜਾਵੇਗੀ")
    .replace(/ਰਿਸਾਅ ([A-Z]) ਵੀ ਲਗਾਤਾਰ ਕੰਮ ਕਰਦੀ ਹੈ/g, "ਰਿਸਾਅ $1 ਵੀ ਲਗਾਤਾਰ ਕੰਮ ਕਰਦਾ ਹੈ")
    .replace(/ਰਿਸਾਅ ([A-Z]) ਇਕੱਲੀ ਪੂਰੀ ਭਰੀ ਟੈਂਕੀ ਖਾਲੀ ਕਰਨ ਵਿੱਚ ਕਿੰਨਾ ਸਮਾਂ ਲਵੇਗੀ\?/g, "ਰਿਸਾਅ $1 ਇਕੱਲਾ ਪੂਰੀ ਭਰੀ ਟੈਂਕੀ ਨੂੰ ਖਾਲੀ ਕਰਨ ਵਿੱਚ ਕਿੰਨਾ ਸਮਾਂ ਲਵੇਗਾ?")
    .replace(/ਅਣਜਾਣ: ਰਿਸਾਅ ([A-Z]) ਦਾ ਇਕੱਲੀ ਕੰਮ ਕਰਨ ਦਾ ਸਮਾਂ।/g, "ਅਣਜਾਣ: ਰਿਸਾਅ $1 ਨੂੰ ਇਕੱਲੇ ਟੈਂਕੀ ਖਾਲੀ ਕਰਨ ਲਈ ਲੱਗਣ ਵਾਲਾ ਸਮਾਂ।")
    .replace(/ਅਣਜਾਣ: ਭਰਨ ਵਾਲੀ ਪਾਈਪ ([A-Z]) ਦਾ ਇਕੱਲੀ ਕੰਮ ਕਰਨ ਦਾ ਸਮਾਂ।/g, "ਅਣਜਾਣ: ਭਰਨ ਵਾਲੀ ਪਾਈਪ $1 ਵੱਲੋਂ ਇਕੱਲੀ ਟੈਂਕੀ ਭਰਨ ਦਾ ਸਮਾਂ।")
    .replace(/ਟੈਂਕੀ ਪੂਰੀ ਤਰ੍ਹਾਂ ਭਰ ਹੋਣ ਵਿੱਚ/g, "ਟੈਂਕੀ ਦੇ ਪੂਰੀ ਤਰ੍ਹਾਂ ਭਰਨ ਵਿੱਚ")
    .replace(/ਟੀਚਾ ਸੀਮਾ: ਪੂਰੀ ਤਰ੍ਹਾਂ ਭਰ।/g, "ਟੀਚਾ ਸੀਮਾ: ਪੂਰਾ ਭਰਾਅ।")
    .replace(/ਜਾਂਚੀ ਜਾ ਰਹੀ ਸੀਮਾ: ਪੂਰੀ ਤਰ੍ਹਾਂ ਭਰ।/g, "ਜਾਂਚੀ ਜਾ ਰਹੀ ਸੀਮਾ: ਪੂਰਾ ਭਰਾਅ।")
    .replace(/ਪਾਣੀ ਦੇ ਪੱਧਰ ਨਾਲ ਕੀ ਹੋਵੇਗਾ\?/g, "ਪਾਣੀ ਦਾ ਪੱਧਰ ਵਧੇਗਾ, ਘਟੇਗਾ ਜਾਂ ਸਥਿਰ ਰਹੇਗਾ?")
    .replace(/tank per (?:ਘੰਟਾ|ਘੰਟੇ)/g, "ਟੈਂਕੀ ਪ੍ਰਤੀ ਘੰਟਾ")
    .replace(/litres\/ਘੰਟਾ/g, "ਲੀਟਰ/ਘੰਟਾ")
    .replace(/litres\/ਮਿੰਟ/g, "ਲੀਟਰ/ਮਿੰਟ")
    .replace(/litres/g, "ਲੀਟਰ")
    .replace(/required level change/g, "ਲੋੜੀਂਦਾ ਪੱਧਰ ਬਦਲਾਅ")
    .replace(/level change needed/g, "ਲੋੜੀਂਦਾ ਪੱਧਰ ਬਦਲਾਅ")
    .replace(/lost efficiency/g, "ਦੱਖਤਾ ਦੀ ਘਾਟ")
    .replace(/blockage/g, "ਰੁਕਾਵਟ")
    .replace(/tank fills/g, "ਟੈਂਕੀ ਭਰਦੀ ਹੈ")
    .replace(/tank empties/g, "ਟੈਂਕੀ ਖਾਲੀ ਹੁੰਦੀ ਹੈ")
    .replace(/level is unchanged/g, "ਪਾਣੀ ਦਾ ਪੱਧਰ ਅਪਰਿਵਰਤਿਤ ਰਹਿੰਦਾ ਹੈ")
    .replace(/boundary is not reached within the window/g, "ਉਪਲਬਧ ਸਮੇਂ ਵਿੱਚ ਸੀਮਾ ਤੱਕ ਨਹੀਂ ਪਹੁੰਚਦੀ");
}

export function polishTmwCp009Text(
  text: string,
  language: TmwLocalizedLanguage,
): string {
  const normalized = normalizeMixedFractions(text);
  return language === "hi" ? polishHindi(normalized) : polishPunjabi(normalized);
}
