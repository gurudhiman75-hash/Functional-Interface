function reviewedText(value: string, locale: PncStudentLocale): string {
  if (locale === "hi-IN") return value.replace(/अधिक-से-अधिक/g, "अधिकतम");
  return value
    .replace(/ਕੈਟੇਗਰੀ/g, "ਵਰਗ")
    .replace(/ਸ਼੍ਰੇਣੀ/g, "ਵਰਗ")
    .replace(/ਖੁੱਲ੍ਹੇ ਤੌਰ ਉੱਤੇ/g, "ਆਪਣੀ ਮਰਜ਼ੀ ਨਾਲ");
}

function numericTokens(value: string): string[] {
  return [...value.matchAll(/\d[\d,]*/g)].map((match) => match[0]!);
}

function mathTokens(value: string): string[] {
  return [...value.matchAll(/\$\$[\s\S]*?\$\$|\$[^$\n]+\$/g)].map((match) => match[0]!);
}

function fill(template: string, numeric: string[], math: string[], qlId: string): string {
  return template.replace(/\{m(\d+)\}|\{(\d+)\}/g, (_, mathIndex: string | undefined, numericIndex: string | undefined) => {
    const value = mathIndex !== undefined ? math[Number(mathIndex)] : numeric[Number(numericIndex)];
    if (value === undefined) throw new Error(`${qlId}: missing varied-opening token`);
    return value;
  });
}

