function tokens(value: string): string[] { return [...value.matchAll(/\d[\d,]*/g)].map((m) => m[0]!); }
function maths(value: string): string[] { return [...value.matchAll(/\$\$[\s\S]*?\$\$|\$[^$\n]+\$/g)].map((m) => m[0]!); }
function fill(template: string, numeric: string[], math: string[], qlId: string): string {
  return template.replace(/\{m(\d+)\}|\{(\d+)\}/g, (_, mi: string | undefined, ni: string | undefined) => {
    const value = mi !== undefined ? math[Number(mi)] : numeric[Number(ni)];
    if (value === undefined) throw new Error(`${qlId}: missing localization token`);
    return value;
  });
}

type Family = "named" | "quota" | "range" | "complement" | "three" | "relation" | "subset" | "namedQuota" | "inverse";
function familyFor(qlId: string): Family {
  const n = Number(qlId.slice(-3));
  if (n <= 152) return "named";
  if (n <= 154) return "quota";
  if (n <= 157 || n >= 175) return "range";
  if (n <= 159) return "complement";
  if (n <= 161) return "three";
  if (n <= 166) return "relation";
  if (n <= 168 || n === 173 || n === 174) return "subset";
  if (n <= 170) return "namedQuota";
  return "inverse";
}

