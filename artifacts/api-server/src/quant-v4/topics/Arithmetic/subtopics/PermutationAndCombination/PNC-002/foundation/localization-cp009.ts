function getSection(sections: PncStudentExplanationSection[], kind: PncStudentExplanationSection["kind"]): PncStudentExplanationSection {
  const section = sections.find((candidate) => candidate.kind === kind);
  if (!section) throw new Error(`PNC CP-009 English presentation is missing ${kind}`);
  return section;
}
function formulaPhrase(values: string[], locale: PncStudentLocale): string {
  if (!values.length) return "";
  return locale === "hi-IN" ? ` यहाँ ${values.join(" तथा ")} प्राप्त होता है।` : ` ਇੱਥੇ ${values.join(" ਅਤੇ ")} ਮਿਲਦਾ ਹੈ।`;
}
function optionIndex(line: string, fallback: number): number {
  const match = line.match(/Option\s+([A-D])/i);
  return match ? match[1]!.toUpperCase().charCodeAt(0) - 65 : fallback;
}

