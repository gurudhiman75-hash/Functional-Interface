function reviewedStem(source: PncStudentSourcePackage, locale: PncStudentLocale): string {
  const qlNumber = Number(source.questionLanguageId.slice(-3));
  if (!Number.isInteger(qlNumber) || qlNumber < 177 || qlNumber > 208) {
    throw new Error(`${source.questionLanguageId}: outside CP-010 reviewed localisation range`);
  }
  const english = buildPnc002ProductionTeacherStudentPresentation(source);
  const template = STEMS[locale][qlNumber - 177];
  if (!template) throw new Error(`${source.questionLanguageId}: reviewed stem is missing`);
  return fill(template, numericTokens(english.stem), mathTokens(english.stem), source.questionLanguageId);
}

function replaceFirstStep(line: string, hint: string, locale: PncStudentLocale): string {
  const label = locale === "hi-IN" ? "शर्त समझें" : "ਸ਼ਰਤ ਸਮਝੋ";
  const formula = mathTokens(line);
  const suffix = formula.length
    ? locale === "hi-IN" ? ` यहाँ ${formula.join(" तथा ")} प्राप्त होता है।` : ` ਇੱਥੇ ${formula.join(" ਅਤੇ ")} ਮਿਲਦਾ ਹੈ।`
    : "";
  return `1. **${label}:** ${hint}${suffix}`;
}

export function buildPnc002Cp010LocalizedPresentation(
  source: PncStudentSourcePackage,
  locale: PncStudentLocale,
): PncLocalizedStudentPresentation {
  const candidate = buildCandidatePresentation(source, locale);
  const qlNumber = Number(source.questionLanguageId.slice(-3));
  const index = qlNumber - 177;
  const title = TITLES[locale][index];
  const hint = HINTS[locale][index];
  if (!title || !hint) throw new Error(`${source.questionLanguageId}: reviewed teaching copy is missing`);

  return {
    ...candidate,
    stem: reviewedStem(source, locale),
    optionUnit: naturalText(candidate.optionUnit, locale),
    displayOptions: candidate.displayOptions.map((option) => naturalText(option, locale)),
    answerLabel: naturalText(candidate.answerLabel, locale),
    explanationSections: candidate.explanationSections.map((section) => {
      if (section.kind === "coreConcept") {
        return {
          ...section,
          heading: locale === "hi-IN" ? `📌 मूल अवधारणा — ${title}` : `📌 ਮੁੱਖ ਵਿਚਾਰ — ${title}`,
          lines: [hint, ...section.lines.slice(1).map((line) => naturalText(line, locale))],
        };
      }
      if (section.kind === "stepByStep") {
        return {
          ...section,
          lines: section.lines.map((line, stepIndex) => stepIndex === 0
            ? replaceFirstStep(line, hint, locale)
            : naturalText(line, locale)),
        };
      }
      return {
        ...section,
        heading: naturalText(section.heading, locale),
        lines: section.lines.map((line) => naturalText(line, locale)),
      };
    }),
    editorialStatus: "PENDING",
    publiclyPublishable: false,
  };
}
