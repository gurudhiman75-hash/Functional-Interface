function numericTokens(value: string): string[] {
  return [...value.matchAll(/-?\d+(?:,\d{3})*/g)].map((match) => match[0]!);
}

function mathTokens(value: string): string[] {
  return [
    ...value.matchAll(/\$\$[\s\S]*?\$\$|\$[^$\n]+\$|\\\([\s\S]*?\\\)|\\\[[\s\S]*?\\\]/g),
  ].map((match) => match[0]!);
}

function fill(
  template: string,
  numbers: readonly string[],
  maths: readonly string[],
  qlId: string,
): string {
  return template.replace(/\{m(\d+)\}|\{(\d+)\}/g, (_match, mathIndex: string | undefined, numberIndex: string | undefined) => {
    const value = mathIndex !== undefined ? maths[Number(mathIndex)] : numbers[Number(numberIndex)];
    if (value === undefined) throw new Error(`${qlId}: missing reviewed localisation token`);
    return value;
  });
}

function naturalText(value: string, locale: PncStudentLocale): string {
  if (locale === "hi-IN") {
    return value
      .replace(/समावेशन–बहिष्करण/g, "जोड़-घटाव वाला गिनती का तरीका")
      .replace(/दर्पण सममिति/g, "शीशे से बनने वाले समान रूप")
      .replace(/घुमाव और दर्पण सममिति/g, "घुमाव और शीशे से बनने वाले समान रूप")
      .replace(/मामल(?:ा|े|ों)/g, "चयन");
  }
  return value
    .replace(/ਪੂਰਕ ਜਾਂ ਸ਼ਾਮਲ–ਬਾਹਰ ਗਿਣਤੀ ਵਰਤੋ/g, "ਕੁੱਲ ਵਿੱਚੋਂ ਮਨ੍ਹਾ ਚੋਣਾਂ ਘਟਾਓ ਜਾਂ ਦੋਹਰੀ ਗਿਣਤੀ ਠੀਕ ਕਰੋ")
    .replace(/ਮਨ੍ਹਾਂ/g, "ਮਨ੍ਹਾ")
    .replace(/ਅਟੱਲ/g, "ਇੱਕ ਥਾਂ ਪੱਕਾ")
    .replace(/ਘੁਮਾਵ ਅਤੇ ਸ਼ੀਸ਼ਾ ਸਮਮਿਤੀ/g, "ਘੁਮਾਵ ਅਤੇ ਸ਼ੀਸ਼ੇ ਨਾਲ ਬਣਦੇ ਇੱਕੋ ਰੂਪ")
    .replace(/ਮਾਮਲ(?:ਾ|ੇ|ਿਆਂ)/g, "ਚੋਣ");
}

