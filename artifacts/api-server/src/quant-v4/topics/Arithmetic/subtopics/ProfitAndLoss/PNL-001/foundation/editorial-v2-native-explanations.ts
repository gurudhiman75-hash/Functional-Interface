function profiles(language: NativeEditorialLanguage) {
  return language === "hi" ? HINDI_PROFILES : PUNJABI_PROFILES;
}

export function buildNativeFriendlyExplanation(input: NativeExplanationInput): FriendlyExplanation {
  const number = qlNumber(input.qlId);
  const family = familyFor(input.solveMode, input.answerSemantic);
  const profile = profiles(input.language)[family];
  const openings = input.language === "hi" ? HINDI_OPENINGS : PUNJABI_OPENINGS;
  const englishSteps = input.englishExplanation.steps;
  const stepCount = Math.max(2, englishSteps.length);
  const steps = Array.from({ length: stepCount }, (_, index) => ({
    title: profile.titles[index % profile.titles.length],
    body: profile.bodies[index % profile.bodies.length],
    equationLatex: englishSteps[index]?.equationLatex,
  }));

  return {
    opening: openings[number % openings.length],
    concept: input.nativeConcept?.trim() || profile.concept,
    steps,
    conclusion: profile.conclusion,
    finalAnswerLatex: input.englishExplanation.finalAnswerLatex,
    commonTrap: profile.trap,
    shortcut: number % 4 === 0 ? profile.shortcut : undefined,
  };
}
