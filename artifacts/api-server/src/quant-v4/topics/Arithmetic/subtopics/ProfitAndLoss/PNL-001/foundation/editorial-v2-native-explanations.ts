function qlNumber(qlId: string): number {
  const value = Number(qlId.split("-").at(-1));
  return Number.isFinite(value) ? value : 1;
}

function familyFor(solveMode: string, answerSemantic: string): ExplanationFamily {
  const key = `${solveMode} ${answerSemantic}`.toUpperCase();
  if (/DATA_SUFFICIENCY|CORRECT_STATEMENT|ALGEBRAIC/.test(key)) return "DATA_REASONING";
  if (/BREAK_EVEN|TARGET_PROFIT_QUANTITY|MARGIN_OF_SAFETY|CONTRIBUTION/.test(key)) return "BREAK_EVEN";
  if (/RECOVERY|REQUIRED_RATE_AFTER_LOSS|NET_TARGET|COMMISSION/.test(key)) return "RECOVERY";
  if (/EFFECTIVE_COST|OVERHEAD|MANUFACTURING|WASTAGE|SCRAP/.test(key)) return "EFFECTIVE_COST";
  if (/FALSE|SHORT|DISHONEST|CHARGE|DELIVER|WEIGHT|MEASURE/.test(key)) return "DISHONEST_TRADE";
  if (/INVENTORY|LOTS|GROUP|STOCK|DAMAGED|SPOILED|FREE_UNITS|EQUAL_SP_TWO|EQUAL_CP_TWO/.test(key)) return "INVENTORY";
  if (/CASHBACK|COUPON|BUY_X|OFFER|DISCOUNT_VS|ELIGIBILITY/.test(key)) return "PROMOTION";
  if (/SUCCESSIVE|STAGES|CHAIN|TRANSACTION|EQUAL_RATE_N_STAGE/.test(key)) return "SUCCESSIVE_CHANGE";
  if (/MARGIN|FRACTION|RATIO|RATE_TO_FRACTION/.test(key)) return "BASE_CONVERSION";
  if (/TO_CP|INITIAL_CP|FINAL_SP_AND|SP_RATE_TO_CP|AMOUNT_RATE_TO_CP/.test(key)) return "REVERSE_PRICE";
  if (/TO_SP|SELLING_PRICE|FINAL_SP|EFFECTIVE_PRICE/.test(key)) return "FORWARD_PRICE";
  if (/TO_RATE|PERCENT|DISCOUNT_PERCENT/.test(key)) return "BASIC_RATE";
  if (/AMOUNT|DIFFERENCE|NET_RESULT/.test(key)) return "BASIC_AMOUNT";
  return "FORWARD_PRICE";
}

