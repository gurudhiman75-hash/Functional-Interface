import type { Avg001QuestionPackage } from "./types";

type Lang = "hi" | "pa";

export function polishAvg001LocalizedStemVariation(
  pkg: Avg001QuestionPackage,
  language: Lang,
): Avg001QuestionPackage {
  const id = Number(pkg.questionLanguageId.slice(-3));
  let stem = pkg.stem;

  if (language === "hi") {
    if (id === 57) {
      stem = stem.replace(
        /^(₹[\d,.]+) के कुल लेन-देन में प्रति लेन-देन औसत (₹[\d,.]+) है। कुल कितने लेन-देन हुए\?$/,
        "लेन-देन की कुल राशि $1 है और प्रति लेन-देन औसत $2 है। लेन-देन की संख्या निकालिए।",
      );
    }
    if (id === 68) {
      stem = stem.replace(
        /^संयंत्र की (\d+) पालियों में प्रति पाली औसत उत्पादन ([\d,.]+) इकाइयाँ है। (\d+) पालियों का कुल उत्पादन ([\d,.]+) है; अंतिम पाली का उत्पादन निकालिए।$/,
        "संयंत्र में $1 पालियों के दौरान प्रति पाली औसतन $2 इकाइयों का उत्पादन हुआ। $3 पालियों का कुल उत्पादन $4 है; अंतिम पाली का उत्पादन निकालिए।",
      );
    }
    if (id === 69) {
      stem = stem.replace(
        /^दुकान की (\d+) दिनों में औसत दैनिक बिक्री (₹[\d,.]+) है। शुरुआती (\d+) दिनों की कुल बिक्री (₹[\d,.]+) है; अंतिम दिन की बिक्री निकालिए।$/,
        "दुकान में $1 दिनों की औसत दैनिक बिक्री $2 है। शुरुआती $3 दिनों की कुल बिक्री $4 है; अंतिम दिन की बिक्री निकालिए।",
      );
    }
    if (id === 206) {
      stem = stem.replace(
        /^खिलाड़ी का (\d+) पारियों में औसत ([\d,.]+) रन है। अगली पारी के ([\d,.]+) रन जोड़ने पर नया औसत निकालिए।$/,
        "खिलाड़ी का $1 पारियों के बाद औसत $2 रन है। अगली पारी में $3 रन बनाने पर नया औसत निकालिए।",
      );
    }
  } else {
    if (id === 57) {
      stem = stem.replace(
        /^(₹[\d,.]+) ਦੇ ਕੁੱਲ ਲੈਣ-ਦੇਣ ਵਿੱਚ ਪ੍ਰਤੀ ਲੈਣ-ਦੇਣ ਔਸਤ (₹[\d,.]+) ਹੈ। ਕੁੱਲ ਕਿੰਨੇ ਲੈਣ-ਦੇਣ ਹੋਏ\?$/,
        "ਲੈਣ-ਦੇਣ ਦੀ ਕੁੱਲ ਰਕਮ $1 ਹੈ ਅਤੇ ਪ੍ਰਤੀ ਲੈਣ-ਦੇਣ ਔਸਤ $2 ਹੈ। ਲੈਣ-ਦੇਣ ਦੀ ਗਿਣਤੀ ਕੱਢੋ।",
      );
    }
    if (id === 68) {
      stem = stem.replace(
        /^ਪਲਾਂਟ ਦੀਆਂ (\d+) ਸ਼ਿਫਟਾਂ ਵਿੱਚ ਪ੍ਰਤੀ ਸ਼ਿਫਟ ਔਸਤ ਉਤਪਾਦਨ ([\d,.]+) ਇਕਾਈਆਂ ਹੈ। (\d+) ਸ਼ਿਫਟਾਂ ਦਾ ਕੁੱਲ ਉਤਪਾਦਨ ([\d,.]+) ਹੈ; ਆਖਰੀ ਸ਼ਿਫਟ ਦਾ ਉਤਪਾਦਨ ਕੱਢੋ।$/,
        "ਪਲਾਂਟ ਵਿੱਚ $1 ਸ਼ਿਫਟਾਂ ਦੌਰਾਨ ਪ੍ਰਤੀ ਸ਼ਿਫਟ ਔਸਤਨ $2 ਇਕਾਈਆਂ ਦਾ ਉਤਪਾਦਨ ਹੋਇਆ। $3 ਸ਼ਿਫਟਾਂ ਦਾ ਕੁੱਲ ਉਤਪਾਦਨ $4 ਹੈ; ਆਖਰੀ ਸ਼ਿਫਟ ਦਾ ਉਤਪਾਦਨ ਕੱਢੋ।",
      );
    }
    if (id === 69) {
      stem = stem.replace(
        /^ਦੁਕਾਨ ਦੀ (\d+) ਦਿਨਾਂ ਵਿੱਚ ਔਸਤ ਰੋਜ਼ਾਨਾ ਵਿਕਰੀ (₹[\d,.]+) ਹੈ। ਸ਼ੁਰੂਆਤੀ (\d+) ਦਿਨਾਂ ਦੀ ਕੁੱਲ ਵਿਕਰੀ (₹[\d,.]+) ਹੈ; ਆਖਰੀ ਦਿਨ ਦੀ ਵਿਕਰੀ ਕੱਢੋ।$/,
        "ਦੁਕਾਨ ਵਿੱਚ $1 ਦਿਨਾਂ ਦੀ ਔਸਤ ਰੋਜ਼ਾਨਾ ਵਿਕਰੀ $2 ਹੈ। ਸ਼ੁਰੂਆਤੀ $3 ਦਿਨਾਂ ਦੀ ਕੁੱਲ ਵਿਕਰੀ $4 ਹੈ; ਆਖਰੀ ਦਿਨ ਦੀ ਵਿਕਰੀ ਕੱਢੋ।",
      );
    }
    if (id === 206) {
      stem = stem.replace(
        /^ਖਿਡਾਰੀ ਦੀ (\d+) ਪਾਰੀਆਂ ਵਿੱਚ ਔਸਤ ([\d,.]+) ਦੌੜਾਂ ਹੈ। ਅਗਲੀ ਪਾਰੀ ਦੀਆਂ ([\d,.]+) ਦੌੜਾਂ ਜੋੜਨ ਉੱਤੇ ਨਵੀਂ ਔਸਤ ਕੱਢੋ।$/,
        "ਖਿਡਾਰੀ ਦੀ $1 ਪਾਰੀਆਂ ਤੋਂ ਬਾਅਦ ਔਸਤ $2 ਦੌੜਾਂ ਹੈ। ਅਗਲੀ ਪਾਰੀ ਵਿੱਚ $3 ਦੌੜਾਂ ਬਣਾਉਣ ਉੱਤੇ ਨਵੀਂ ਔਸਤ ਕੱਢੋ।",
      );
    }
  }

  return {
    ...pkg,
    stem,
    traceability: {
      ...pkg.traceability,
      localizedStemVariationPolish: "AVG-001 localized stem variation polish v1",
    },
  };
}
