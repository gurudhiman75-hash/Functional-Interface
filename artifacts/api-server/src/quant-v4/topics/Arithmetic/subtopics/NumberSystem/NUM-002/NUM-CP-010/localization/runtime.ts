function translate(value: string, language: NumCp010LocalizedLanguage): string {
  let out = value;
  for (const [pattern, replacement] of language === "hi" ? HI : PA) out = out.replace(pattern, replacement);
  return out;
}

function finalSentence(answer: string, language: NumCp010LocalizedLanguage): string {
  return language === "hi" ? `अंतिम उत्तर: ${answer}।` : `ਅੰਤਿਮ ਉੱਤਰ: ${answer}।`;
}

export function generateNumCp010Localized(
  qlId: NumCp010PermanentQlId,
  seed: number,
  language: NumCp010LocalizedLanguage,
): NumCp010LocalizedPackage {
  const source = generateNumCp010Permanent(qlId, seed);
  const localized = Object.freeze({
    ...source,
    locale: language === "hi" ? "hi-IN" as const : "pa-IN" as const,
    language,
    stem: translate(source.stem, language),
    explanation: Object.freeze({
      coreConcept: translate(source.explanation.coreConcept, language),
      strategy: translate(source.explanation.strategy, language),
      steps: Object.freeze(source.explanation.steps.map((step) => translate(step, language))),
      finalAnswer: finalSentence(source.canonicalAnswer, language),
    }),
    lifecycle: Object.freeze({
      ...source.lifecycle,
      reviewStatus: "HI_PA_REVIEW_CANDIDATE" as const,
    }),
  });
  return localized as NumCp010LocalizedPackage;
}
