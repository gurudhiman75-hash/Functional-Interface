import { strict as assert } from "node:assert";
import { readFileSync } from "node:fs";
import {
  getRap003ActiveCanonicalProblemIds,
  getRap003QuestionLanguageIds,
  getRap003RegistryEntry,
} from "../../RatioAndProportion/RAP-003";
import { generatePrt001E13Parameters } from "./foundation/e13-parameter-generator";
import {
  getPrt001QuestionLanguageIds,
  getPrt001TaskEntry,
} from "./foundation/library";
import { runPrt001PilotPipeline } from "./foundation/pipeline";

export interface Prt001E13CrossChapterOwnershipReport {
  readonly audit: string;
  readonly cases: number;
  readonly metrics: Readonly<Record<string, unknown>>;
}

export function auditPrt001E13CrossChapterOwnership(): Prt001E13CrossChapterOwnershipReport {
  const activePrtQlIds = new Set(getPrt001QuestionLanguageIds());
  assert.equal(activePrtQlIds.size, 112, "E13 ownership audit expects the 112-QL Partnership surface.");

  // G06: pure SI/CI stays with INT; the mixed capital-interest -> residual-profit
  // distribution contract is explicitly owned and generated by Partnership.
  const ql111Entry = getPrt001TaskEntry("PRT-QL-111");
  assert.equal(ql111Entry.cpId, "PRT-CP-006");
  assert.equal(ql111Entry.taskKind, "interestOnCapitalThenResidualShare");
  assert.equal(ql111Entry.solveMode, "findPartnerReceiptsWithMultipleOrderedAllocations");

  const ql111Params = generatePrt001E13Parameters({
    questionLanguageId: "PRT-QL-111",
    seed: "e13-g06-cross-chapter-ownership",
    entry: ql111Entry,
    language: "en",
  });
  assert.equal(ql111Params.state.allocations.length, 2);
  assert.equal(
    ql111Params.state.allocations.every(
      (allocation) =>
        allocation.kind === "INTEREST_ON_CAPITAL" &&
        allocation.basis === "PERCENT_OF_PARTNER_CAPITAL" &&
        Boolean(allocation.recipientPartnerId),
    ),
    true,
    "G06 must preserve first-class partner-capital percentage semantics.",
  );
  const ql111 = runPrt001PilotPipeline({
    questionLanguageId: "PRT-QL-111",
    seed: "e13-g06-cross-chapter-ownership",
    language: "en",
  });
  assert.equal(ql111.validation.valid, true);
  assert.equal(ql111.canonicalProblemId, "PRT-CP-006");
  assert.equal(ql111.traceability.expansionWave, "E13");

  // Keep this ownership assertion independent of INT runtime compilation. INT has
  // its own active localization/typecheck lifecycle; PRT only needs to prove that
  // INT's declared boundary remains pure interest and does not claim G06.
  const intOwnership = readFileSync(
    new URL("../../Interest/INT-001/INT-001-SOURCE-AND-OWNERSHIP-AUDIT.md", import.meta.url),
    "utf8",
  );
  assert.match(
    intOwnership,
    /Partnership owns profit sharing by capital and time\./,
    "INT ownership ledger must continue to assign partnership profit-sharing semantics to Partnership.",
  );
  assert.match(
    intOwnership,
    /INT must not treat partnership contribution-time products as interest\./,
    "INT ownership ledger must explicitly reject contribution-time Partnership semantics.",
  );
  const intPreRegistrationAdapter = readFileSync(
    new URL("../../Interest/INT-001/int-001-cp001-question-studio-pre-registration-adapter.ts", import.meta.url),
    "utf8",
  );
  assert.match(intPreRegistrationAdapter, /packageId:\s*"INT-001"/);
  assert.match(intPreRegistrationAdapter, /id:\s*"INT-CP-001"/);
  assert.match(intPreRegistrationAdapter, /subtopic:\s*"Simple Interest"/);
  assert.match(intPreRegistrationAdapter, /questionStudioDiscoverable:\s*false/);
  assert.doesNotMatch(
    intPreRegistrationAdapter,
    /PRT-CP-006|interestOnCapitalThenResidualShare|PERCENT_OF_PARTNER_CAPITAL/,
    "INT CP001 pre-registration surface must not claim the mixed G06 Partnership contract.",
  );

  // G07: arithmetic-only incoming-partner share acquisition is now a PRT product
  // contract. RAP may own generic ratios, but it must not re-expose Partnership.
  const ql112Entry = getPrt001TaskEntry("PRT-QL-112");
  assert.equal(ql112Entry.cpId, "PRT-CP-005");
  assert.equal(ql112Entry.taskKind, "incomingPartnerProfitShareAcquisition");
  assert.equal(ql112Entry.solveMode, "findProfitRatioAfterNewPartnerAcquiresShare");
  const ql112 = runPrt001PilotPipeline({
    questionLanguageId: "PRT-QL-112",
    seed: "e13-g07-cross-chapter-ownership",
    language: "en",
  });
  assert.equal(ql112.validation.valid, true);
  assert.equal(ql112.answerType, "RATIO");
  assert.equal(ql112.canonicalProblemId, "PRT-CP-005");
  assert.equal(ql112.traceability.expansionWave, "E13");

  const activeRapCps = getRap003ActiveCanonicalProblemIds();
  assert.equal(activeRapCps.includes("RAP-CP-013"), false, "Legacy RAP Partnership CP013 must remain retired.");
  let activeRapQlCount = 0;
  for (const cpId of activeRapCps) {
    for (const qlId of getRap003QuestionLanguageIds(cpId)) {
      activeRapQlCount += 1;
      const rapEntry = getRap003RegistryEntry(qlId);
      assert.notEqual(
        rapEntry.taskKind,
        ql112Entry.taskKind,
        `${cpId}:${qlId} must not duplicate the G07 incoming-partner Partnership contract.`,
      );
    }
  }

  return {
    audit: "e13-cross-chapter-ownership",
    cases: activeRapQlCount + 2,
    metrics: {
      activePrtQls: activePrtQlIds.size,
      g06: {
        productOwner: "PRT-001",
        qlId: "PRT-QL-111",
        allocationBasis: "PERCENT_OF_PARTNER_CAPITAL",
        pureInterestOwner: "INT-001",
        intMixedPartnershipSurfaceClaimed: false,
      },
      g07: {
        productOwner: "PRT-001",
        qlId: "PRT-QL-112",
        legacyRapPartnershipCpActive: false,
        activeRapQlCount,
      },
    },
  };
}
