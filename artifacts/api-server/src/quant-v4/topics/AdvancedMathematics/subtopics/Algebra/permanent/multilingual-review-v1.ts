function localizeQuestion(locale: AlgReviewLocale, question: string): string {
  const languageRules = locale === "hi-IN" ? HI_QUESTION_RULES : PA_QUESTION_RULES;
  const commonRules = locale === "hi-IN" ? HI_COMMON_RULES : PA_COMMON_RULES;
  return applyRules(applyRules(question, languageRules), commonRules)
    .replace(/\s+([।?])/g, "$1")
    .trim();
}

function localizeExplanationLine(locale: AlgReviewLocale, line: string): string {
  const explanationRules = locale === "hi-IN" ? HI_EXPLANATION_RULES : PA_EXPLANATION_RULES;
  const commonRules = locale === "hi-IN" ? HI_COMMON_RULES : PA_COMMON_RULES;
  return applyRules(applyRules(line.trim(), explanationRules), commonRules).trim();
}

function localizeExplanation(locale: AlgReviewLocale, explanation: string): string {
  return explanation
    .split(/\n+/)
    .map((line) => localizeExplanationLine(locale, line))
    .filter(Boolean)
    .join("\n");
}

export function generateAlgPermanentMultilingualReviewV1(
  qlId: AlgPermanentQlId,
  seed: number,
  locale: AlgReviewLocale,
  requestedVariantIndex?: number,
): AlgPermanentMultilingualReviewV1Item {
  const english = generateAlgPermanentEnglishV3Frozen(qlId, seed, requestedVariantIndex);

  if (!english.englishImplementationFrozen || english.multilingualImplementationFrozen) {
    throw new Error(`${qlId}: multilingual review must derive from frozen English V3 and remain pre-multilingual-freeze`);
  }
  if (english.active || english.questionStudioDiscoverable || english.questionBankWritable || english.testEligible || english.publiclyPublishable) {
    throw new Error(`${qlId}: downstream lifecycle leaked into multilingual review`);
  }

  return {
    ...english,
    localizationReviewId: ALG_MULTILINGUAL_REVIEW_V1_ID,
    sourceEnglishFreezeId: ALG_ENGLISH_V3_FREEZE_ID,
    locale,
    language: locale === "hi-IN" ? "hi" : "pa",
    englishQuestion: english.question,
    englishExplanation: english.explanation,
    question: localizeQuestion(locale, english.question),
    explanation: localizeExplanation(locale, english.explanation),
    maturity: "MULTILINGUAL_REVIEW_CANDIDATE_V1",
    reviewStatus: "HUMAN_LOCALIZATION_REVIEW_REQUIRED",
    multilingualImplementationFrozen: false,
  };
}
