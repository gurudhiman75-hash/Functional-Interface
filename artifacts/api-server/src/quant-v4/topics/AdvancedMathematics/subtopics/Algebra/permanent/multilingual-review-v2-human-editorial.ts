function polishQuestion(item: AlgPermanentMultilingualReviewV2Item): string {
  let value = item.question;
  if (item.locale === "hi-IN") {
    value = value
      .replace(/^α और β के मूल हैं (.+)।/, "α और β, $1 के मूल हैं।")
      .replace(/^α, β और γ के मूल हैं (.+)।/, "α, β और γ, $1 के मूल हैं।");
  } else {
    value = value
      .replace(/^α ਅਤੇ β ਦੇ ਮੂਲ ਹਨ (.+)\./, "α ਅਤੇ β, $1 ਦੇ ਮੂਲ ਹਨ.")
      .replace(/^α, β ਅਤੇ γ ਦੇ ਮੂਲ ਹਨ (.+)\./, "α, β ਅਤੇ γ, $1 ਦੇ ਮੂਲ ਹਨ.");
  }
  return value;
}

