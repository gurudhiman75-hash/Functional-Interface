function sha256(value: unknown) {
  return createHash("sha256")
    .update(typeof value === "string" ? value : JSON.stringify(value), "utf8")
    .digest("hex");
}

function finish(value: unknown) {
  return String(value ?? "")
    .replace(/\s+([,;:!?])/gu, "$1")
    .replace(/,{2,}/gu, ",")
    .replace(/\s{2,}/gu, " ")
    .replace(/\.\s*$/u, "।")
    .trim();
}

