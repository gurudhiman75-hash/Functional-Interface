#!/usr/bin/env python3
"""Compile native stem sources into TypeScript.

Usage: python3 compile_native_stems.py <sources/menNNN.tsv> <out.ts> <ExportName>

Source lines (tab separated):  key <TAB> hindi template <TAB> punjabi template
  key = "<patternId>|<English skeleton>"  (exact wording)   or   "<patternId>#<slotCount>"  (all wordings of the pattern)
Templates use {1}, {2}, ... for the n-th number/math token of the English stem.
Every slot must be used in both templates, in the same left-to-right order as the English stem.
"""
import json, re, sys

src, out, name = sys.argv[1:4]
rows = {}
for lineno, line in enumerate(open(src, encoding="utf-8"), 1):
    line = line.rstrip("\n")
    if not line.strip() or line.startswith("#"):
        continue
    parts = line.split("\t")
    if len(parts) != 3:
        sys.exit(f"{src}:{lineno}: expected 3 tab-separated columns, got {len(parts)}")
    key, hi, pa = parts
    count = int(key.split("#")[1]) if "#" in key and "|" not in key else len(set(re.findall(r"\{(\d+)\}", key.split("|", 1)[1])))
    for lang, text in (("hi", hi), ("pa", pa)):
        used = [int(x) for x in re.findall(r"\{(\d+)\}", text)]
        if sorted(set(used)) != list(range(1, count + 1)):
            sys.exit(f"{src}:{lineno}: {lang} template of {key} must use slots 1..{count}, uses {sorted(set(used))}")
        if used != sorted(used):
            sys.exit(f"{src}:{lineno}: {lang} template of {key} reorders numbers (the math-parity test needs English order)")
    rows[key] = (hi, pa)

body = ",\n".join(f"  {json.dumps(k, ensure_ascii=False)}: [{json.dumps(v[0], ensure_ascii=False)}, {json.dumps(v[1], ensure_ascii=False)}]" for k, v in sorted(rows.items()))
header = (
    "// Generated by tools/compile_native_stems.py. Do not edit by hand.\n"
    "// Key: `${patternId}|${English skeleton}` or `${patternId}#${slotCount}` -> [Hindi template, Punjabi template].\n"
)
open(out, "w", encoding="utf-8").write(header + f"export const {name}: Readonly<Record<string, readonly [string, string]>> = {{\n{body}{',' if body else ''}\n}};\n")
print(f"{len(rows)} templates -> {out}")
