import type { MenCp009NativeV2Language } from "./editorial-v2";

export function naturalizeMenCp009NativeStemV3(
  value: string,
  language: MenCp009NativeV2Language,
) {
  if (language === "hi") {
    return value
      .replace(/एक गोले का सतह का क्षेत्रफल/g, "एक गोले की सतह का क्षेत्रफल")
      .replace(/उसका सतह का क्षेत्रफल/g, "उसकी सतह का क्षेत्रफल")
      .replace(/उसके सतह का क्षेत्रफल में/g, "उसकी सतह के क्षेत्रफल में")
      .replace(/दो गोलों के सतह का क्षेत्रफलों/g, "दो गोलों की सतह के क्षेत्रफलों")
      .replace(/उनके सतह का क्षेत्रफलों/g, "उनकी सतह के क्षेत्रफलों")
      .replace(/गोले के सतह का क्षेत्रफल/g, "गोले की सतह का क्षेत्रफल")
      .replace(/अर्धगोले के कुल सतह का क्षेत्रफल/g, "अर्धगोले की कुल सतह का क्षेत्रफल")
      .replace(/सतह का क्षेत्रफलों/g, "सतह के क्षेत्रफलों")
      .replace(/\s+/g, " ")
      .trim();
  }

  return value
    .replace(/ਅਰਧ ਵਿਆਸ/g, "ਅਰਧ-ਵਿਆਸ")
    .replace(/ਇੱਕ ਗੋਲੇ ਦਾ ਸਤਹ ਦਾ ਖੇਤਰਫਲ/g, "ਇੱਕ ਗੋਲੇ ਦੀ ਸਤਹ ਦਾ ਖੇਤਰਫਲ")
    .replace(/ਇਸ ਦਾ ਸਤਹ ਦਾ ਖੇਤਰਫਲ/g, "ਇਸ ਦੀ ਸਤਹ ਦਾ ਖੇਤਰਫਲ")
    .replace(/ਇਸ ਦੇ ਸਤਹ ਦਾ ਖੇਤਰਫਲ ਵਿੱਚ/g, "ਇਸ ਦੀ ਸਤਹ ਦੇ ਖੇਤਰਫਲ ਵਿੱਚ")
    .replace(/ਗੋਲੇ ਦੇ ਸਤਹ ਦਾ ਖੇਤਰਫਲ/g, "ਗੋਲੇ ਦੀ ਸਤਹ ਦਾ ਖੇਤਰਫਲ")
    .replace(/ਅਰਧ-ਗੋਲੇ ਦੇ ਕੁੱਲ ਸਤਹ ਦਾ ਖੇਤਰਫਲ/g, "ਅਰਧ-ਗੋਲੇ ਦੀ ਕੁੱਲ ਸਤਹ ਦਾ ਖੇਤਰਫਲ")
    .replace(/ਉਨ੍ਹਾਂ ਦੇ ਸਤਹ ਦਾ ਖੇਤਰਫਲਾਂ/g, "ਉਨ੍ਹਾਂ ਦੀ ਸਤਹ ਦੇ ਖੇਤਰਫਲਾਂ")
    .replace(/ਸਤਹ ਦਾ ਖੇਤਰਫਲਾਂ/g, "ਸਤਹ ਦੇ ਖੇਤਰਫਲਾਂ")
    .replace(/ਦੋ ਗੋਲਿਆਂ ਦੇ ਸਤਹ ਦੇ ਖੇਤਰਫਲਾਂ/g, "ਦੋ ਗੋਲਿਆਂ ਦੀ ਸਤਹ ਦੇ ਖੇਤਰਫਲਾਂ")
    .replace(/ਉਨ੍ਹਾਂ ਦੇ ਸਤਹ ਦੇ ਖੇਤਰਫਲਾਂ/g, "ਉਨ੍ਹਾਂ ਦੀ ਸਤਹ ਦੇ ਖੇਤਰਫਲਾਂ")
    .replace(/\s+/g, " ")
    .trim();
}
