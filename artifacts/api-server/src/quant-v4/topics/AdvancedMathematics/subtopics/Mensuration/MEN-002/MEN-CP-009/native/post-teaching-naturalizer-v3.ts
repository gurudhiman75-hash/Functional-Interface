function hindi(value: string) {
  return value
    .replace(/^त्रिज्याएँ (\d+) और (\d+), इसलिए start के साथ (\d+):(\d+)\.$/, "त्रिज्याएँ $1 और $2 हैं, इसलिए पहले अनुपात $3:$4 लिखें।")
    .replace(/^सरल करें अनुपात करने पर (.+)\.$/, "अनुपात को सरल करने पर $1 मिलता है।")
    .replace(/^इसलिए, अनुपात of radii है (.+)\.$/, "अतः त्रिज्याओं का अनुपात $1 है।")
    .replace(/^(\d+(?:\.\d+)?)% बढ़ने पर नई त्रिज्या पुरानी त्रिज्या की ([\d.]+) गुना old त्रिज्या\.$/, "$1% बढ़ने पर नई त्रिज्या, पुरानी त्रिज्या की $2 गुना हो जाती है।")
    .replace(/^For a अर्धगोला, curved सतह का क्षेत्रफल = (.+?) और आयतन = (.+)\.$/, "अर्धगोले के लिए वक्र सतह का क्षेत्रफल = $1 और आयतन = $2।")
    .replace(/^For a solid अर्धगोला, TSA = (.+?) और आयतन = (.+)\.$/, "ठोस अर्धगोले के लिए कुल सतह का क्षेत्रफल = $1 और आयतन = $2।")
    .replace(/^For a solid अर्धगोला, TSA : आयतन simplifies to (.+)\.$/, "ठोस अर्धगोले के लिए कुल सतह का क्षेत्रफल : आयतन सरल होकर $1 मिलता है।")
    .replace(/^For these matching क्षेत्रफल और आयतन formulas, क्षेत्रफल : आयतन simplifies to (.+)\.$/, "इन क्षेत्रफल और आयतन के सूत्रों को भाग देने पर क्षेत्रफल : आयतन सरल होकर $1 मिलता है।")
    .replace(/^दिए हुए अनुपात (.+?) के साथ (.+)\.$/, "दिए हुए अनुपात $1 को $2 के बराबर रखें।")
    .replace(/^क्षेत्रफल : आयतन लिखें और दोनों में समान (.+)\.$/, "क्षेत्रफल : आयतन लिखें और दोनों में समान $1 को काट दें।")
    .replace(/^भाग देने पर TSA by आयतन cancels (.+?), leaving (.+)\.$/, "कुल सतह के क्षेत्रफल को आयतन से भाग देने पर $1 कट जाता है और $2 बचता है।")
    .replace(/^For same त्रिज्या, गोला आयतन है (.+?) और अर्धगोला आयतन है (.+)\.$/, "समान त्रिज्या के लिए गोले का आयतन $1 और अर्धगोले का आयतन $2 होता है।")
    .replace(/^For same त्रिज्या, गोला सतह का क्षेत्रफल है (.+?) और अर्धगोला total क्षेत्रफल है (.+)\.$/, "समान त्रिज्या के लिए गोले की सतह का क्षेत्रफल $1 और अर्धगोले की कुल सतह का क्षेत्रफल $2 होता है।")
    .replace(/^इसलिए आयतन (.+)\.$/, "इसलिए आयतन में वृद्धि $1 है।")
    .replace(/^इसलिए सतह का क्षेत्रफल (.+)\.$/, "इसलिए सतह के क्षेत्रफल में वृद्धि $1 है।")
    .replace(/^इसलिए, अनुपात (?:of )?radii है (.+)\.$/, "अतः त्रिज्याओं का अनुपात $1 है।")
    .replace(/\blitres\b/gi, "लीटर")
    .replace(/\btimes\b/gi, "गुना")
    .replace(/\bold\b/gi, "पुरानी")
    .replace(/\bstart\b/gi, "पहले")
    .replace(/\bFor\b/g, "")
    .replace(/\bcurved\b/gi, "वक्र")
    .replace(/\bsolid\b/gi, "ठोस")
    .replace(/\bsimplifies\b/gi, "सरल होकर")
    .replace(/\bof\b/gi, "का")
    .replace(/\bradii\b/gi, "त्रिज्याओं")
    .replace(/\bto get\b/gi, "से")
    .replace(/\s+/g, " ")
    .trim();
}

