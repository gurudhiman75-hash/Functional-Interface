function escapeRegex(value: string) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function protectMathAndIds(text: string) {
  const protectedValues: string[] = [];
  const protect = (value: string) => {
    const token = `⟦M${protectedValues.length}⟧`;
    protectedValues.push(value);
    return token;
  };
  let result = text
    .replace(/\$\$[\s\S]*?\$\$/g, protect)
    .replace(/\$[^$]*\$/g, protect)
    .replace(/\\\([\s\S]*?\\\)/g, protect)
    .replace(/\[[A-Z0-9_:-]{3,}\]/g, protect);
  return { result, protectedValues };
}

function restoreProtected(text: string, protectedValues: readonly string[], language: MensurationLocalizedLanguage) {
  let result = text;
  protectedValues.forEach((value, index) => {
    let localized = value;
    if (language === "hi") {
      localized = localized
        .replace(/\\text\{litres?\}/g, "\\text{लीटर}")
        .replace(/\\text\{tiles?\}/g, "\\text{टाइल}")
        .replace(/\\text\{revolutions?\}/g, "\\text{चक्कर}");
    } else {
      localized = localized
        .replace(/\\text\{litres?\}/g, "\\text{ਲੀਟਰ}")
        .replace(/\\text\{tiles?\}/g, "\\text{ਟਾਈਲ}")
        .replace(/\\text\{revolutions?\}/g, "\\text{ਚੱਕਰ}");
    }
    result = result.replace(`⟦M${index}⟧`, localized);
  });
  return result;
}

function applyPhrasePairs(text: string, pairs: readonly PhrasePair[]) {
  let result = text;
  const sorted = [...pairs].sort((a, b) => b[0].length - a[0].length);
  for (const [source, target] of sorted) {
    if (!source) continue;
    const alphaOnly = /^[A-Za-z][A-Za-z' -]*[A-Za-z]$/.test(source);
    const pattern = alphaOnly
      ? new RegExp(`\\b${escapeRegex(source)}\\b`, "gi")
      : new RegExp(escapeRegex(source), "gi");
    result = result.replace(pattern, target);
  }
  return result;
}

function normalizeLocalizedPunctuation(text: string, language: MensurationLocalizedLanguage) {
  let result = text
    .replace(/[ \t]+([,.;:?])/g, "$1")
    .replace(/ {2,}/g, " ")
    .replace(/\n +/g, "\n")
    .replace(/ +\n/g, "\n")
    .replace(/\.\./g, ".")
    .replace(/,\s*,/g, ",");
  if (language === "hi") {
    result = result
      .replace(/एक है /g, "एक ")
      .replace(/ है है/g, " है")
      .replace(/ हैं हैं/g, " हैं")
      .replace(/का का/g, "का")
      .replace(/के साथ के साथ/g, "के साथ")
      .replace(/ज्ञात करें कीजिए/g, "ज्ञात कीजिए")
      .replace(/गणना करें करें/g, "गणना करें");
  } else {
    result = result
      .replace(/ਇੱਕ ਹੈ /g, "ਇੱਕ ")
      .replace(/ ਹੈ ਹੈ/g, " ਹੈ")
      .replace(/ ਹਨ ਹਨ/g, " ਹਨ")
      .replace(/ਦਾ ਦਾ/g, "ਦਾ")
      .replace(/ਦੇ ਨਾਲ ਦੇ ਨਾਲ/g, "ਦੇ ਨਾਲ")
      .replace(/ਪਤਾ ਕਰੋ ਕਰੋ/g, "ਪਤਾ ਕਰੋ")
      .replace(/ਗਣਨਾ ਕਰੋ ਕਰੋ/g, "ਗਣਨਾ ਕਰੋ");
  }
  return result.trim();
}

export function localizeMensurationProse(text: string, language: MensurationLocalizedLanguage) {
  if (!text) return text;
  const { result: protectedText, protectedValues } = protectMathAndIds(text);
  const translated = applyPhrasePairs(protectedText, language === "hi" ? HI_PHRASES : PA_PHRASES);
  return normalizeLocalizedPunctuation(restoreProtected(translated, protectedValues, language), language);
}

