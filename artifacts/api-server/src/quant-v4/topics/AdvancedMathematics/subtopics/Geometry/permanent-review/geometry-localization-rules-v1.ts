function cleanup(value: string, locale: GeometryReviewLocaleV1): string {
  let out = value
    .replace(/\s{2,}/g, " ")
    .replace(/\s+([,;:?])/g, "$1")
    .replace(/\s+\./g, ".")
    .trim();
  if (locale === "hi-IN" || locale === "pa-IN") {
    out = out.replace(/\.(?=\s|$)/g, "।");
  }
  return out;
}

export function localizeGeometryLearnerTextV1(
  input: string,
  locale: GeometryReviewLocaleV1,
  kind: "question" | "option" | "explanation" = "explanation",
): string {
  const structural = locale === "hi-IN" ? HI_STRUCTURAL_RULES : PA_STRUCTURAL_RULES;
  const lexical = locale === "hi-IN" ? HI_RULES : PA_RULES;
  const optionRules = locale === "hi-IN" ? HI_OPTION_RULES : PA_OPTION_RULES;
  let value = input;
  if (kind === "question") value = applyRules(value, structural);
  if (kind === "option") value = applyRules(value, optionRules);
  value = applyRules(value, lexical);
  return cleanup(value, locale);
}
