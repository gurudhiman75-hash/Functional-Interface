import type {
  FormulaQuestion,
  Pattern,
} from "../core/generator-engine";
import {
  isQuantV2PercentageEnabled,
  isQuantV2PercentagePattern,
} from "./percentage-admin-adapter";

export type QuantV2IntegrationValidationResult = {
  valid: boolean;
  issues: string[];
  metrics: {
    adapterCompatibility: number;
    adminWorkflowCompatibility: number;
    multilingualIntegrity: number;
    svgIntegrity: number;
    metadataMapping: number;
    validatorPropagation: number;
    fallbackRoutingSafety: number;
  };
};

function hasText(value: unknown) {
  return typeof value === "string" && value.trim().length > 0;
}

function hasNativeHindi(value: unknown) {
  return typeof value === "string" && /[\u0900-\u097F]/u.test(value);
}

function hasNativePunjabi(value: unknown) {
  return typeof value === "string" && /[\u0A00-\u0A7F]/u.test(value);
}

function score(passed: boolean) {
  return passed ? 100 : 0;
}

function debug(question: FormulaQuestion) {
  return (question.debugMetadata ?? {}) as Record<string, unknown>;
}

function quantV2Payload(question: FormulaQuestion) {
  return debug(question).quantV2 as Record<string, unknown> | undefined;
}

export function validateQuantV2AdminIntegration(
  question: FormulaQuestion,
): QuantV2IntegrationValidationResult {
  const issues: string[] = [];
  const quantV2 = quantV2Payload(question);
  const hasAdapter =
    debug(question).generationDomain === "quant-v2-percentage" &&
    Boolean(quantV2);
  const hasAdminShape =
    hasText(question.text) &&
    Array.isArray(question.options) &&
    question.options.length >= 4 &&
    Number.isInteger(question.correct) &&
    question.correct >= 0 &&
    question.correct < question.options.length &&
    hasText(question.explanation);
  const hasMultilingual =
    hasText(question.textHi) &&
    hasNativeHindi(question.textHi) &&
    hasText(question.explanationHi) &&
    hasText(question.textPa) &&
    hasNativePunjabi(question.textPa) &&
    hasText(question.explanationPa);
  const svgRendering =
    (question.svgRendering as Record<string, unknown> | undefined) ??
    (quantV2?.svgRendering as Record<string, unknown> | undefined);
  const hasSvg =
    hasText(svgRendering?.svg) &&
    String(svgRendering?.svg).includes("<svg");
  const hasMetadata =
    Boolean(question.reasoningGraph ?? quantV2?.reasoningGraph) &&
    Boolean(question.semanticMetadata ?? quantV2?.semanticMetadata) &&
    Boolean(question.qualityMetrics ?? quantV2?.qualityMetrics) &&
    Boolean(question.localizationMetadata ?? quantV2?.localizationMetadata) &&
    Boolean(question.pedagogicalMetrics ?? quantV2?.pedagogicalMetrics);
  const validatorReports =
    (quantV2?.validatorReports as Record<string, unknown> | undefined) ??
    ((question as any).proceduralLogic?.validatorReports as
      | Record<string, unknown>
      | undefined);
  const hasValidators =
    Boolean(validatorReports?.canonical) &&
    Boolean(validatorReports?.reasoningGraph) &&
    Boolean(validatorReports?.localization) &&
    Boolean(validatorReports?.svg);

  if (!hasAdapter) {
    issues.push("Question was not generated by the quant-v2 percentage adapter.");
  }
  if (!hasAdminShape) {
    issues.push("Question does not satisfy the existing admin question shape.");
  }
  if (!hasMultilingual) {
    issues.push("Hindi/Punjabi quant-v2 renderings are missing or still using English stems.");
  }
  if (!hasSvg) {
    issues.push("SVG rendering is missing or incomplete.");
  }
  if (!hasMetadata) {
    issues.push("Quant-v2 optional metadata was not mapped onto the admin payload.");
  }
  if (!hasValidators) {
    issues.push("Quant-v2 validator reports were not propagated.");
  }

  const metrics = {
    adapterCompatibility: score(hasAdapter),
    adminWorkflowCompatibility: score(hasAdminShape),
    multilingualIntegrity: score(hasMultilingual),
    svgIntegrity: score(hasSvg),
    metadataMapping: score(hasMetadata),
    validatorPropagation: score(hasValidators),
    fallbackRoutingSafety: 100,
  };

  return {
    valid: issues.length === 0,
    issues,
    metrics,
  };
}

export function validateQuantV2FallbackRouting(pattern: Pattern) {
  const shouldRouteToQuantV2 =
    isQuantV2PercentageEnabled() &&
    isQuantV2PercentagePattern(pattern);

  return {
    valid: shouldRouteToQuantV2,
    issues: shouldRouteToQuantV2
      ? []
      : ["Feature flag or pattern detection would route this pattern to legacy quant."],
    metrics: {
      fallbackRoutingSafety: shouldRouteToQuantV2 ? 100 : 70,
    },
  };
}
