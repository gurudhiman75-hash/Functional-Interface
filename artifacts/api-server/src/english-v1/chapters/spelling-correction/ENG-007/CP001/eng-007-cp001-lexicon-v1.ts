function sortedLetters(value:string){return value.toLowerCase().split("").sort().join("");}
function inferTrap(correct:string,wrong:string):Eng007Trap{
  const c=correct.toLowerCase(),w=wrong.toLowerCase();
  if(c.length===w.length+1)return "omitted-letter";
  if(w.length===c.length+1)return "extra-letter";
  if(c.length===w.length&&sortedLetters(c)===sortedLetters(w))return "letter-order";
  if(/[aeiou]{2}/.test(c)||/(ie|ei)/.test(c))return "vowel-pattern";
  if(/([bcdfghjklmnpqrstvwxyz])\1/.test(c))return "consonant-pattern";
  if(/(ance|ence|able|ible|ary|ery|tion|sion|ous|ious|ant|ent|ment|ness|ful|ally|ially)$/.test(c))return "ending-pattern";
  return "general-pattern";
}

