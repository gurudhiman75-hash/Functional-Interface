function placeCorrect(
  correct: string,
  distractors: readonly [string, string, string],
  correctIndex: number,
): string[] {
  const options = [...distractors];
  options.splice(correctIndex, 0, correct);
  if (options.length !== 4 || new Set(options).size !== 4) {
    throw new Error("ENV-CP-002 requires four unique options");
  }
  return options;
}

export function generateEnvCp002ReviewBatchV1(): EnvCp002ReviewQuestion[] {
  return REVIEW_SEEDS_V1.map((seed, index) => {
    const correctIndex = CORRECT_POSITIONS[index % CORRECT_POSITIONS.length];
    const options = placeCorrect(seed.correct, seed.distractors, correctIndex);

    return {
      questionId: `ENV-CP002-V1-${String(index + 1).padStart(3, "0")}`,
      chapterId: "ENV-001",
      cpId: "ENV-CP-002",
      qlId: seed.qlId,
      qlName: seed.qlName,
      difficulty: seed.difficulty,
      stem: seed.stem,
      options,
      correctIndex,
      canonicalAnswer: seed.correct,
      explanation: seed.explanation,
      sourceIds: [SOURCE_ID],
      sourceFactIds: [...seed.sourceFactIds],
      reviewOnly: true,
      runtimeRegistered: false,
    };
  });
}
