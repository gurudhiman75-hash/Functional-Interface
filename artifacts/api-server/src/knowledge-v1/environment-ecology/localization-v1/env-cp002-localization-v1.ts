function native(text: string, locale: NativeLocale): string {
  const value = O[text]?.[locale];
  if (value) return value;

  if (text.includes(" → ")) return text.split(" → ").map((part) => native(part, locale)).join(" → ");
  if (text.includes(" — ")) return text.split(" — ").map((part) => native(part, locale)).join(" — ");
  if (text.includes(", ")) return text.split(", ").map((part) => native(part, locale)).join(", ");
  throw new Error(`ENV-CP-002 localization missing option: ${text}`);
}

function localizedBase(
  q: (typeof ENV_CP002_ENGLISH_AUTHORITY_V1)[number],
  locale: EnvLocaleV1,
  stem: string,
  options: string[],
  canonicalAnswer: string,
  explanation: string,
): EnvLocalizedQuestionV1 {
  return {
    ...q,
    questionId: locale === "en" ? q.questionId : `${q.questionId}-${locale.toUpperCase()}`,
    stem,
    options,
    canonicalAnswer,
    explanation,
    locale,
    localizationV1: {
      version: ENV_LOCALIZATION_V1,
      englishQuestionId: q.questionId,
      semanticInvariant: true,
      cpInvariant: true,
      qlInvariant: true,
      difficultyInvariant: true,
      sourceInvariant: true,
      optionOrderInvariant: true,
      correctIndexInvariant: true,
      reviewOnly: true,
    },
  };
}

export function generateEnvCp002LocalizedReviewV1(locale: EnvLocaleV1): EnvLocalizedQuestionV1[] {
  if (locale === "en") {
    return ENV_CP002_ENGLISH_AUTHORITY_V1.map((q) =>
      localizedBase(q, locale, q.stem, [...q.options], q.canonicalAnswer, q.explanation),
    );
  }

  const stems = locale === "hi" ? STEM_HI : STEM_PA;
  const explanations = locale === "hi" ? EXPL_HI : EXPL_PA;
  if (stems.length !== ENV_CP002_ENGLISH_AUTHORITY_V1.length || explanations.length !== ENV_CP002_ENGLISH_AUTHORITY_V1.length) {
    throw new Error("ENV-CP-002 localization text count does not match English authority");
  }

  return ENV_CP002_ENGLISH_AUTHORITY_V1.map((q, index) => {
    const options = q.options.map((value) => native(value, locale));
    return localizedBase(q, locale, stems[index], options, options[q.correctIndex], explanations[index]);
  });
}

export const ENV_CP002_MULTILINGUAL_V1 = Object.freeze({
  en: generateEnvCp002LocalizedReviewV1("en"),
  hi: generateEnvCp002LocalizedReviewV1("hi"),
  pa: generateEnvCp002LocalizedReviewV1("pa"),
});
