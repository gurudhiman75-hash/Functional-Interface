function native(text:string,locale:NativeLocale):string{
  const v=O[text]?.[locale];
  if(v) return v;
  for(const sep of [" → "," — "]){
    if(text.includes(sep)) return text.split(sep).map(part=>native(part,locale)).join(sep);
  }
  throw new Error(`ENV-CP-003 localization missing option: ${text}`);
}

function localizedBase(q:(typeof ENV_CP003_ENGLISH_AUTHORITY_V1)[number],locale:EnvLocaleV1,stem:string,options:string[],canonicalAnswer:string,explanation:string):EnvLocalizedQuestionV1{
  return {
    ...q,
    questionId:locale==="en"?q.questionId:`${q.questionId}-${locale.toUpperCase()}`,
    stem,options,canonicalAnswer,explanation,locale,
    localizationV1:{
      version:ENV_LOCALIZATION_V1,englishQuestionId:q.questionId,
      semanticInvariant:true,cpInvariant:true,qlInvariant:true,difficultyInvariant:true,sourceInvariant:true,
      optionOrderInvariant:true,correctIndexInvariant:true,reviewOnly:true,
    },
  };
}

export function generateEnvCp003LocalizedReviewV1(locale:EnvLocaleV1):EnvLocalizedQuestionV1[]{
  if(locale==="en") return ENV_CP003_ENGLISH_AUTHORITY_V1.map(q=>localizedBase(q,locale,q.stem,[...q.options],q.canonicalAnswer,q.explanation));
  const stems=locale==="hi"?STEM_HI:STEM_PA;
  const explanations=locale==="hi"?EXPL_HI:EXPL_PA;
  if(stems.length!==48||explanations.length!==48) throw new Error("ENV-CP-003 localization count mismatch");
  return ENV_CP003_ENGLISH_AUTHORITY_V1.map((q,i)=>{
    const options=q.options.map(v=>native(v,locale));
    return localizedBase(q,locale,stems[i],options,options[q.correctIndex],explanations[i]);
  });
}

export const ENV_CP003_MULTILINGUAL_V1=Object.freeze({
  en:generateEnvCp003LocalizedReviewV1("en"),
  hi:generateEnvCp003LocalizedReviewV1("hi"),
  pa:generateEnvCp003LocalizedReviewV1("pa"),
});
