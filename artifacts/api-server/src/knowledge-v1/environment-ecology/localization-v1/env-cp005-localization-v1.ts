function native(text: string, locale: NativeLocale): string {
  const direct = O[text]?.[locale];
  if (direct) return direct;
  if (text.includes(" — ")) return text.split(" — ").map((part) => native(part, locale)).join(" — ");
  throw new Error(`ENV-CP-005 localization missing option: ${text}`);
}

function base(q: (typeof ENV_CP005_ENGLISH_AUTHORITY_V1)[number], locale: EnvLocaleV1, stem: string, options: string[], explanation: string): EnvLocalizedQuestionV1 {
  return {
    ...q,
    questionId: locale === "en" ? q.questionId : `${q.questionId}-${locale.toUpperCase()}`,
    stem,
    options,
    canonicalAnswer: options[q.correctIndex],
    explanation,
    locale,
    localizationV1: {
      version: ENV_LOCALIZATION_V1,
      englishQuestionId: q.questionId,
      semanticInvariant: true,
      cpInvariant: true,
      qlInvariant: true,
      difficultyInvariant: true,
      sourceInvariant: true,
      optionOrderInvariant: true,
      correctIndexInvariant: true,
      reviewOnly: true,
    },
  };
}

export function generateEnvCp005LocalizedReviewV1(locale: EnvLocaleV1): EnvLocalizedQuestionV1[] {
  if (locale === "en") return ENV_CP005_ENGLISH_AUTHORITY_V1.map((q) => base(q, locale, q.stem, [...q.options], q.explanation));
  const stems = locale === "hi" ? STEM_HI : STEM_PA;
  const explanations = locale === "hi" ? EXPL_HI : EXPL_PA;
  if (stems.length !== 48 || explanations.length !== 48) throw new Error("ENV-CP-005 localization count mismatch");
  return ENV_CP005_ENGLISH_AUTHORITY_V1.map((q, i) => base(q, locale, stems[i], q.options.map((v) => native(v, locale)), explanations[i]));
}

export const ENV_CP005_MULTILINGUAL_V1 = Object.freeze({
  en: generateEnvCp005LocalizedReviewV1("en"),
  hi: generateEnvCp005LocalizedReviewV1("hi"),
  pa: generateEnvCp005LocalizedReviewV1("pa"),
});
