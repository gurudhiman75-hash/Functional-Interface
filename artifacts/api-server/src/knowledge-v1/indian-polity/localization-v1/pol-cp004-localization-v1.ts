function option(text: string, locale: NativeLocale): string {
  const am = text.match(/^Article (\d+[A-Z]?)$/);
  if (am) return ARTICLE(am[1]!, locale);
  const article = articleBySubject(text);
  if (article) return native(SUBJECTS[article]!, locale);
  if (COMMON[text]) return native(COMMON[text]!, locale);
  if (ART20_MEANING[text]) return native(ART20_MEANING[text]!, locale);
  if (ART22[text]) return native(ART22[text]!, locale);
  const writ = WRITS[text];
  if (writ) return native(writ.name, locale);
  const purposeWrit = Object.entries(POL_CP004_WRITS_V1).find?.(() => false);
  for (const row of POL_CP004_WRITS_V1) if (row.purpose === text) return native(WRITS[row.writ]!.purpose, locale);
  throw new Error(`Untranslated POL-CP-004 option: ${text}`);
}

