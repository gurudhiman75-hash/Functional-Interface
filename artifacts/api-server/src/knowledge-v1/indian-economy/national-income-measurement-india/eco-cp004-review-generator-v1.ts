function makeQuestion(ql: number, rowIndex: number, globalIndex: number): EcoCp004ReviewQuestion {
  const qlId = `ECO-004-QL-${String(ql).padStart(3, "0")}`;
  const correctTarget = globalIndex % 4;
  const difficulty = difficultyForVariant(ql, rowIndex);
  let stem = "";
  let correct = "";
  let options: string[] = [];
  let explanation = "";
  let metadata = sources(methods[0]);

  if (ql === 1) {
    const row = methodVariants[rowIndex % methodVariants.length];
    stem = row.stem;
    correct = row.answer;
    options = moveCorrect([...methodOptions], correct, correctTarget);
    explanation = row.explanation;
    metadata = sources(row.row);
  } else if (ql === 2) {
    const row = scenarioVariants[rowIndex % scenarioVariants.length];
    stem = row.stem;
    correct = row.answer;
    options = moveCorrect([...methodOptions], correct, correctTarget);
    explanation = row.explanation;
    metadata = sources(...row.rows);
  } else if (ql === 3) {
    const row = uses[rowIndex % uses.length];
    stem = `${row.description} is treated as:`;
    correct = row.classification;
    options = moveCorrect(["Final", "Intermediate", "Transfer payment", "Net export"], correct, correctTarget);
    explanation = `${row.classification}: ${row.reason}.`;
    metadata = sources(row);
  } else if (ql === 4) {
    const row = doubleCountingVariants[rowIndex % doubleCountingVariants.length];
    stem = row.stem;
    correct = row.answer;
    options = moveCorrect([...row.options], correct, correctTarget);
    explanation = row.explanation;
    metadata = {
      sourceIds: [...rules.sourceIds],
      sourceFactIds: ["eco-cp004-value-added-method", "eco-cp004-intermediate-use"],
    };
  } else if (ql === 5) {
    const row = ECO_CP004_VALUE_ADDED_CASES_V1[rowIndex % ECO_CP004_VALUE_ADDED_CASES_V1.length];
    if (rowIndex < 2) {
      stem = `Output is ${row.output} and intermediate consumption is ${row.intermediate}. Value added is:`;
      correct = row.answer;
      options = moveCorrect([row.answer, String(row.output), String(row.intermediate), String(row.output + row.intermediate)], correct, correctTarget);
      explanation = `${row.output} - ${row.intermediate} = ${row.answer}.`;
    } else if (rowIndex === 2) {
      stem = `Output is ${row.output} and value added is ${row.answer}. Intermediate consumption is:`;
      correct = String(row.intermediate);
      options = moveCorrect([correct, row.answer, String(row.output), String(row.output + row.intermediate)], correct, correctTarget);
      explanation = `${row.output} - ${row.answer} = ${row.intermediate}.`;
    } else {
      stem = `Value added is ${row.answer} and intermediate consumption is ${row.intermediate}. Output is:`;
      correct = String(row.output);
      options = moveCorrect([correct, row.answer, String(row.intermediate), String(Number(row.answer) - row.intermediate)], correct, correctTarget);
      explanation = `${row.answer} + ${row.intermediate} = ${row.output}.`;
    }
    metadata = { sourceIds: [...rules.sourceIds], sourceFactIds: ["eco-cp004-value-added-formula"] };
  } else if (ql === 6) {
    const row = expenditureRows[rowIndex % expenditureRows.length];
    stem = `${row.description} is recorded as:`;
    correct = row.component;
    options = moveCorrect(expenditureRows.map((item) => item.component), correct, correctTarget);
    explanation = `${row.description} is part of ${row.component.toLowerCase()}.`;
    metadata = sources(row);
  } else if (ql === 7) {
    const variant = incomeVariants[rowIndex % incomeVariants.length];
    const row = variant.row;
    stem = variant.stem;
    correct = row.component;
    options = moveCorrect(["Compensation of employees", "Operating surplus", "Mixed income", "Net exports"], correct, correctTarget);
    explanation = `${row.component}: ${row.description.toLowerCase()}.`;
    metadata = sources(row);
  } else if (ql === 8) {
    const row = ECO_CP004_GDP_GVA_CASES_V1[rowIndex % ECO_CP004_GDP_GVA_CASES_V1.length];
    if (rowIndex < 2) {
      stem = `Sum of GVA is ${row.gva} and taxes less subsidies on products are ${row.taxesLessSubsidies}. GDP is:`;
      correct = row.answer;
      options = moveCorrect([row.answer, String(row.gva), String(row.gva - row.taxesLessSubsidies), String(row.gva + row.taxesLessSubsidies + 20)], correct, correctTarget);
      explanation = `${row.gva} + ${row.taxesLessSubsidies} = ${row.answer}.`;
    } else {
      const taxes = row.taxesLessSubsidies + 20;
      const subsidies = 20;
      stem = `Sum of GVA is ${row.gva}, product taxes are ${taxes} and product subsidies are ${subsidies}. GDP is:`;
      correct = row.answer;
      options = moveCorrect([row.answer, String(row.gva + taxes), String(row.gva - subsidies), String(row.gva - row.taxesLessSubsidies)], correct, correctTarget);
      explanation = `Net product taxes = ${taxes} - ${subsidies} = ${row.taxesLessSubsidies}; GDP = ${row.gva} + ${row.taxesLessSubsidies} = ${row.answer}.`;
    }
    metadata = { sourceIds: [...rules.sourceIds], sourceFactIds: ["eco-cp004-gdp-gva-relation"] };
  } else if (ql === 9) {
    const row = baseYearVariants[rowIndex % baseYearVariants.length];
    stem = row.stem;
    correct = row.answer;
    options = moveCorrect([...row.options], correct, correctTarget);
    explanation = row.explanation;
    metadata = { sourceIds: [...rules.sourceIds], sourceFactIds: ["eco-cp004-base-year", "eco-cp004-base-revision-purpose"] };
  } else if (ql === 10) {
    if (rowIndex === 0) {
      stem = "National Accounts Statistics in India are published by:";
      correct = "Ministry of Statistics and Programme Implementation (MoSPI)";
      options = moveCorrect([correct, "Ministry of Finance", "Reserve Bank of India", "NITI Aayog"], correct, correctTarget);
      explanation = "MoSPI publishes India's National Accounts Statistics.";
    } else {
      stem = "For official Indian national-accounts estimates, which ministry is the main statistical source?";
      correct = "Ministry of Statistics and Programme Implementation (MoSPI)";
      options = moveCorrect([correct, "Ministry of Commerce and Industry", "Ministry of Labour and Employment", "Ministry of Corporate Affairs"], correct, correctTarget);
      explanation = "MoSPI is the official ministry responsible for national-accounts statistics.";
    }
    metadata = { sourceIds: [...rules.sourceIds], sourceFactIds: ["eco-cp004-mospi-role"] };
  } else if (ql === 11) {
    const row = statementVariants[rowIndex % statementVariants.length];
    stem = `Consider the statements:\nI. ${row.s1}\nII. ${row.s2}\nWhich is correct?`;
    correct = row.answer;
    options = moveCorrect(["I only", "II only", "Both I and II", "Neither I nor II"], correct, correctTarget);
    explanation = row.explanation;
    metadata = { sourceIds: [...rules.sourceIds], sourceFactIds: [...rules.sourceFactIds] };
  } else {
    const row = distinctionVariants[rowIndex % distinctionVariants.length];
    stem = row.stem;
    correct = row.answer;
    options = moveCorrect([...row.options], correct, correctTarget);
    explanation = row.explanation;
    metadata = { sourceIds: [...rules.sourceIds], sourceFactIds: [...rules.sourceFactIds] };
  }

  return {
    questionId: `ECO-CP004-V1-${String(globalIndex + 1).padStart(3, "0")}`,
    chapterId: "ECO-001",
    cpId: "ECO-CP-004",
    qlId,
    qlName: qlNames[ql],
    difficulty,
    stem,
    options,
    correctIndex: correctTarget,
    canonicalAnswer: correct,
    explanation,
    ...metadata,
    reviewOnly: true,
    runtimeRegistered: false,
  };
}

export function generateEcoCp004ReviewBatchV1() {
  const countsByQl: Record<number, number> = {
    1: 4,
    2: 4,
    3: 5,
    4: 4,
    5: 4,
    6: 4,
    7: 4,
    8: 4,
    9: 3,
    10: 2,
    11: 3,
    12: 3,
  };

  const questions: EcoCp004ReviewQuestion[] = [];
  let globalIndex = 0;
  for (let ql = 1; ql <= 12; ql += 1) {
    for (let rowIndex = 0; rowIndex < countsByQl[ql]; rowIndex += 1) {
      questions.push(makeQuestion(ql, rowIndex, globalIndex));
      globalIndex += 1;
    }
  }
  return questions;
}
