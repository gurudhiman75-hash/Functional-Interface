function build(language: Locale, data: typeof HI): readonly LocalizedQuestion[] {
  const locale = language === "hi" ? "hi-IN" : "pa-IN";
  if (data.stems.length !== GEO_WAT_001_CP001_REVIEW_BATCH_V1.length) throw new Error("GEO-WAT-001 CP001 localized stem count mismatch");
  if (data.options.length !== GEO_WAT_001_CP001_REVIEW_BATCH_V1.length) throw new Error("GEO-WAT-001 CP001 localized option count mismatch");
  if (data.explanations.length !== GEO_WAT_001_CP001_REVIEW_BATCH_V1.length) throw new Error("GEO-WAT-001 CP001 localized explanation count mismatch");
  return Object.freeze(GEO_WAT_001_CP001_REVIEW_BATCH_V1.map((source, index) => {
    const options = Object.freeze([...data.options[index]!]);
    if (options.length !== 4) throw new Error("GEO-WAT-001 CP001 localized question must have four options: " + source.questionId);
    return Object.freeze({
      sourceQuestionId: source.questionId,
      qlId: source.qlId,
      difficulty: source.difficulty,
      language,
      locale,
      stem: data.stems[index]!,
      options,
      correctIndex: source.correctIndex,
      canonicalAnswer: options[source.correctIndex]!,
      explanation: data.explanations[index]!,
      sourceIds: Object.freeze([...source.sourceIds]),
      sourceFactIds: Object.freeze([...source.sourceFactIds]),
      reviewOnly: true as const,
      runtimeRegistered: false as const,
    });
  }));
}

export const GEO_WAT_001_CP001_HINDI_LOCALIZATION_V1 = build("hi", HI);
export const GEO_WAT_001_CP001_PUNJABI_LOCALIZATION_V1 = build("pa", PA);

export function auditGeoWat001Cp001LocalizationV1() {
  const issues: string[] = [];
  for (const batch of [GEO_WAT_001_CP001_HINDI_LOCALIZATION_V1, GEO_WAT_001_CP001_PUNJABI_LOCALIZATION_V1]) {
    const seen = new Set<string>();
    for (const q of batch) {
      if (seen.has(q.sourceQuestionId)) issues.push("DUPLICATE:" + q.language + ":" + q.sourceQuestionId);
      seen.add(q.sourceQuestionId);
      if (q.options.length !== 4 || new Set(q.options).size !== 4) issues.push("OPTIONS:" + q.language + ":" + q.sourceQuestionId);
      if (q.options[q.correctIndex] !== q.canonicalAnswer) issues.push("ANSWER:" + q.language + ":" + q.sourceQuestionId);
      if (q.language === "hi" && !/[\u0900-\u097F]/.test(q.stem)) issues.push("NO_HINDI:" + q.sourceQuestionId);
      if (q.language === "pa" && !/[\u0A00-\u0A7F]/.test(q.stem)) issues.push("NO_PUNJABI:" + q.sourceQuestionId);
      if (q.explanation.length < 65) issues.push("SHORT_EXPLANATION:" + q.language + ":" + q.sourceQuestionId);
      if (!q.reviewOnly || q.runtimeRegistered) issues.push("LIFECYCLE:" + q.language + ":" + q.sourceQuestionId);
    }
  }
  return Object.freeze({
    valid: issues.length === 0,
    issues: Object.freeze(issues),
    canonicalQuestionCount: GEO_WAT_001_CP001_REVIEW_BATCH_V1.length,
    hindiQuestionCount: GEO_WAT_001_CP001_HINDI_LOCALIZATION_V1.length,
    punjabiQuestionCount: GEO_WAT_001_CP001_PUNJABI_LOCALIZATION_V1.length,
    localizedOutputCount: GEO_WAT_001_CP001_HINDI_LOCALIZATION_V1.length + GEO_WAT_001_CP001_PUNJABI_LOCALIZATION_V1.length,
    qlCount: new Set(GEO_WAT_001_CP001_REVIEW_BATCH_V1.map((q) => q.qlId)).size,
  });
}
