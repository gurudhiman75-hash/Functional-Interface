import { nativeLocalizedQuestion, assertNativeEnglishSourceParity, nativeExplanationText,
         assertNativeLocalizedAnswerParity } from "./native-linked-localization";
import { listQuestionStudioPackages } from "./engine-registry";
import { nativeSourceQuestion,nativeSourceHash,nativeIdentityHash,type PersistedNativeSnapshot,
         type PersistedNativeVariant } from "./persisted-native-review-format";
const string=(x:unknown)=>typeof x==="string"?x.trim():"";

/** Called during generation, before persisting the immutable English version.
 * A broken native engine is visible as a blocked locale, never mislinked.
 * Source parity failure returns no snapshot at all. */
export async function prepareNativeReviewSnapshot(
  payload:Record<string,unknown>, languages: readonly ("hi"|"pa")[]=["hi","pa"],
):Promise<PersistedNativeSnapshot|null> {
  const packageId=string(payload.packageId);
  const pkg=listQuestionStudioPackages().find(p=>p.enabled&&p.packageId===packageId);
  if(!pkg||string(payload.language)!=="en"||!string(payload.seed)||
     !string(payload.canonicalProblemId||payload.selectedCpId||payload.cpId)||
     !string(payload.questionLanguageId||payload.qlId))return null;
  const active=languages.filter(lang=>pkg.supportedLanguages.includes(lang));
  if(active.length===0)return null;
  const source=nativeSourceQuestion(payload);
  if(!source.stem||!source.explanation||source.options.length<2||
     !Number.isInteger(source.correctIndex)||source.correctIndex<0||
     source.correctIndex>=source.options.length)return null;
  try {
    assertNativeEnglishSourceParity(source,await nativeLocalizedQuestion(payload,"en"));
  }catch(error){
    console.warn("[native-review] English source parity failed; no Hindi/Punjabi saved",{packageId,cpId:string(payload.canonicalProblemId||payload.selectedCpId||payload.cpId),reason:error instanceof Error?error.message:String(error)});
    return null;
  }
  const variants=await Promise.all(active.map(async (language):Promise<PersistedNativeVariant>=>{
    try{
      const localized=await nativeLocalizedQuestion(payload,language);
      assertNativeLocalizedAnswerParity(source,localized);
      return {language,status:"verified",...localized};
    }catch{
      return {language,status:"blocked",reason:"The native generator did not pass canonical answer parity."};
    }
  }));
  return {schemaVersion:1,sourceHash:nativeSourceHash(source),identityHash:nativeIdentityHash(payload),variants,
    generatedAt:new Date().toISOString(),sourceVerified:true};
}


/** When the options are identical in both languages (numbers, formulas, codes) but
 * were shuffled differently, put them in the English order. The correct answer
 * must stay the same option. Wording-dependent explanations are left alone. */
export function alignLocalizedOptions(source:{options:string[];correctIndex:number},
  localized:{stem:string;explanation:string;options:string[];correctIndex:number}) {
  if(localized.correctIndex===source.correctIndex)return localized;
  if(/(option|विकल्प|ਵਿਕਲਪ)\s*\(?[A-Ea-e1-5]\)?|\([A-Ea-e]\)/.test(localized.explanation))return localized;
  const a=[...source.options],b=[...localized.options];
  if(a.length!==b.length)return localized;
  // Same text in both languages, or (units/words translated) the same unique numbers.
  const keyers:Array<(o:string)=>string>=[o=>o,o=>numberList(o).join(",")];
  for(const key of keyers){
    const ka=a.map(key),kb=b.map(key);
    if(ka.some(k=>!k)||new Set(ka).size!==ka.length||new Set(kb).size!==kb.length)continue;
    if([...ka].sort().join("\u0000")!==[...kb].sort().join("\u0000"))continue;
    if(ka[source.correctIndex]!==kb[localized.correctIndex])continue;
    return {...localized,options:ka.map(k=>b[kb.indexOf(k)]!),correctIndex:source.correctIndex};
  }
  return localized;
}

/** Hindi/Punjabi questions generated by the same request as the English one. */
export type NativeCompanions = Partial<Record<"hi"|"pa",Record<string,unknown>|Record<string,unknown>[]>>;
const DIGITS: Record<string,string> = {};
"०१२३४५६७८९".split("").forEach((d,i)=>{DIGITS[d]=String(i);});
"੦੧੨੩੪੫੬੭੮੯".split("").forEach((d,i)=>{DIGITS[d]=String(i);});
const numberList=(value:string)=>(value.replace(/[०-९੦-੯]/g,d=>DIGITS[d]??d).replace(/(\d),(?=\d{3}\b)/g,"$1")
  .match(/\d+(?:\.\d+)?/g)??[]);
/** Every number in the English stem must appear in the localized stem. Extra
 * numbers are allowed (translated labels such as "सूची-1" for "List I"). */
export const numbersCompatible=(english:string,localized:string)=>{
  const pool=numberList(localized);
  for(const token of numberList(english)){const at=pool.indexOf(token);if(at<0)return false;pool.splice(at,1);}
  return true;
};
const idOf=(q:Record<string,unknown>,keys:string[])=>keys.map(k=>string(q[k])).find(Boolean)??"";
/** Some chapters put the language into the question-language ID
 * ("…:en-IN:…", "…-EN-…:hi"). Drop that tag so the same question compares equal. */
export const languageNeutralId=(id:string)=>id
  .replace(/(^|[:_-])(en|hi|pa)(?:[-_]in)?(?=$|[:_-])/gi,"$1")
  .replace(/[:_-]{2,}/g,":").replace(/^[:_-]|[:_-]$/g,"").toLowerCase();

/** Fallback for chapters whose saved question cannot be replayed from a seed.
 * The Hindi/Punjabi question must come from the same request and line up with the
 * English one: same checkpoint and question-language IDs, same correct answer
 * position, same option count and the same numbers. Anything else is blocked. */
export function prepareNativeSnapshotFromCompanions(
  payload:Record<string,unknown>, languages:readonly ("hi"|"pa")[], companions:NativeCompanions,
):PersistedNativeSnapshot|null {
  const packageId=string(payload.packageId);
  const pkg=listQuestionStudioPackages().find(p=>p.enabled&&p.packageId===packageId);
  if(!pkg||string(payload.language)!=="en")return null;
  const active=languages.filter(lang=>pkg.supportedLanguages.includes(lang)&&companions[lang]);
  if(active.length===0)return null;
  const source=nativeSourceQuestion(payload);
  if(!source.stem||!source.explanation||source.options.length<2||
     !Number.isInteger(source.correctIndex)||source.correctIndex<0||
     source.correctIndex>=source.options.length)return null;
  const variants=active.map((language):PersistedNativeVariant=>{
    const raw=companions[language]!;
    const candidates=(Array.isArray(raw)?raw:[raw]).filter(Boolean);
    let lastError:unknown=null;
    for(const companion of candidates){
    try{
      const cpA=idOf(payload,["canonicalProblemId","selectedCpId","cpId"]),cpB=idOf(companion,["canonicalProblemId","selectedCpId","cpId"]);
      const qlA=idOf(payload,["questionLanguageId","qlId"]),qlB=idOf(companion,["questionLanguageId","qlId"]);
      if(cpA&&cpB&&languageNeutralId(cpA)!==languageNeutralId(cpB))throw new Error("checkpoint differs");
      if(qlA&&qlB&&languageNeutralId(qlA)!==languageNeutralId(qlB))throw new Error("question language differs");
      if(string(companion.language)&&string(companion.language)!==language)throw new Error("wrong language");
      const localized={
        stem:string(companion.text)||string(companion.stem),
        explanation:nativeExplanationText(companion.explanation),
        options:Array.isArray(companion.options)?companion.options.map(o=>typeof o==="string"?o.trim():string((o as {text?:unknown})?.text)):[],
        correctIndex:Number(companion.correctIndex??companion.correct),
      };
      const aligned=alignLocalizedOptions(source,localized);
      assertNativeLocalizedAnswerParity(source,aligned);
      if(!numbersCompatible(source.stem,aligned.stem))throw new Error("numbers differ");
      return {language,status:"verified",...aligned};
    }catch(error){lastError=error;}
    }
    console.warn("[native-review] companion rejected",{packageId,language,candidates:candidates.length,reason:lastError instanceof Error?lastError.message:String(lastError)});
    return {language,status:"blocked",reason:"The native generator did not pass canonical answer parity."};
  });
  return {schemaVersion:1,sourceHash:nativeSourceHash(source),identityHash:nativeIdentityHash(payload),variants,
    generatedAt:new Date().toISOString(),sourceVerified:true};
}
/** Which native languages to prepare at generation time.
 * Default: every Hindi/Punjabi language the package supports, so reviewers see all
 * languages instantly. An explicit request list narrows it. Kill switch:
 * EXAMTREE_NATIVE_SNAPSHOT_DISABLED=true restores English-only generation. */
export function nativeLanguagesToPrepare(
  packageId: unknown, requested: unknown, env: Record<string, string | undefined> = process.env,
): ("hi"|"pa")[] {
  if (env.EXAMTREE_NATIVE_SNAPSHOT_DISABLED === "true") return [];
  const pkg = listQuestionStudioPackages().find(p => p.enabled && p.packageId === string(packageId));
  if (!pkg) return [];
  const supported = (["hi","pa"] as const).filter(lang => pkg.supportedLanguages.includes(lang));
  const asked = Array.isArray(requested) ? requested.filter((l): l is "hi"|"pa" => l === "hi" || l === "pa") : [];
  return asked.length ? supported.filter(lang => asked.includes(lang)) : [...supported];
}
/** Small batches of expensive native-language snapshots. No unbounded fanout. */
export async function prepareNativeReviewBatch(
  questions:Record<string,unknown>[], languages:readonly ("hi"|"pa")[]=["hi","pa"],
  /** Called only for questions the seed replay could not prepare. */
  companionsFor?:(question:Record<string,unknown>,index:number)=>Promise<NativeCompanions|undefined>,
) {
  const result:Array<PersistedNativeSnapshot|null>=new Array(questions.length).fill(null);
  let index=0;
  await Promise.all(Array.from({length:Math.min(3,questions.length)},async()=>{
    while(index<questions.length){
      const next=index++;
      try{
        result[next]=await prepareNativeReviewSnapshot(questions[next]!,languages);
        const replayed=result[next];
        const missing=languages.filter(language=>!replayed?.variants.some(v=>v.language===language&&v.status==="verified"));
        if(missing.length&&companionsFor){
          const companions=await companionsFor(questions[next]!,next);
          const fallback=companions&&prepareNativeSnapshotFromCompanions(questions[next]!,missing,companions);
          if(fallback){
            const kept=(replayed?.variants??[]).filter(v=>v.status==="verified");
            const better=fallback.variants.filter(v=>v.status==="verified"||!kept.some(k=>k.language===v.language));
            const merged=[...kept.filter(k=>!better.some(b=>b.language===k.language)),...better]
              .sort((a,b)=>a.language.localeCompare(b.language));
            result[next]={...(replayed??fallback),variants:merged};
          }
        }
      }
      catch(error){
        // Never fail the run, but leave a trace: a missing Hindi/Punjabi snapshot used to be silent.
        console.warn("[native-review] snapshot not prepared",{packageId:string(questions[next]?.packageId),cpId:string(questions[next]?.canonicalProblemId),reason:error instanceof Error?error.message:String(error)});
        result[next]=null;
      }
    }
  }));
  return result;
}
