assert.equal(COM005_STANDARD_BANK_ONLY_PACKAGE_V1.metadata?.hindiQuestionCount,54);
assert.equal(COM005_STANDARD_BANK_ONLY_PACKAGE_V1.metadata?.punjabiQuestionCount,54);
