import { COM005_ENGLISH_FREEZE_AUTHORITY_V1, COM005_LOCALIZATION_FREEZE_AUTHORITY_V1, auditCom005FreezeV1 } from "../../knowledge-v1/computer-awareness/com005-networking-freeze-v1";
