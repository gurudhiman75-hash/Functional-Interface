await commerce.openCommerceCheckout(args);
assert.equal(opens,1);
const key=calls[0].body.idempotencyKey;
await commerce.openCommerceCheckout(args);
assert.equal(calls[1].body.idempotencyKey,key,'retry reuses canonical order key');
await options.handler({razorpay_payment_id:'payment-1',razorpay_signature:'signature',razorpay_order_id:'provider-1'});
